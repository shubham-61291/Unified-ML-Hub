# ----------------------------------------------------------
# 1️⃣ Imports & Setup
# ----------------------------------------------------------
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
from sklearn.datasets import make_classification
from sklearn.preprocessing import StandardScaler
from sklearn.model_selection import train_test_split
from sklearn.ensemble import IsolationForest
from sklearn.svm import OneClassSVM
from sklearn.metrics import (
    confusion_matrix, roc_curve, roc_auc_score, precision_recall_curve,
    auc, classification_report
)
from sklearn.covariance import EmpiricalCovariance
from scipy.stats import zscore
import tensorflow as tf
from tensorflow import keras
from tensorflow.keras import layers
import plotly.express as px

sns.set(style="whitegrid", rc={"figure.figsize":(8,6)})

np.random.seed(42)
tf.random.set_seed(42)

# ----------------------------------------------------------
# 2️⃣ Synthetic Data (with ground truth)
# ----------------------------------------------------------
X, y = make_classification(
    n_samples=3000, n_features=10, n_informative=5, n_redundant=0,
    n_clusters_per_class=1, weights=[0.97], flip_y=0, random_state=42
)
X = StandardScaler().fit_transform(X)

# Inject anomalies
n_outliers = 90
outliers = np.random.uniform(low=-6, high=6, size=(n_outliers, X.shape[1]))
X = np.vstack([X, outliers])
y = np.concatenate([y, np.ones(n_outliers)])

print(f"Dataset shape: {X.shape} | Anomalies: {sum(y==1)} ({sum(y==1)/len(y)*100:.2f}%)")

X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.25, random_state=42, stratify=y
)

# ----------------------------------------------------------
# 3️⃣ Evaluation Function
# ----------------------------------------------------------
def evaluate_anomaly_model(y_true, scores, threshold=None, title="Model"):
    if threshold is None:
        threshold = np.percentile(scores, 95)  # Top 5% anomalies
    y_pred = (scores > threshold).astype(int)

    auc_roc = roc_auc_score(y_true, scores)
    precision, recall, _ = precision_recall_curve(y_true, scores)
    auc_pr = auc(recall, precision)
    cm = confusion_matrix(y_true, y_pred)
    f1 = (2 * cm[1,1]) / (2 * cm[1,1] + cm[0,1] + cm[1,0] + 1e-6)

    print(f"\n🔍 {title}")
    print("-"*40)
    print(f"AUC-ROC: {auc_roc:.4f} | AUC-PR: {auc_pr:.4f} | F1: {f1:.4f}")
    print("\nConfusion Matrix:\n", cm)
    print(classification_report(y_true, y_pred, digits=3))

    # ROC
    fpr, tpr, _ = roc_curve(y_true, scores)
    plt.figure(figsize=(6,5))
    plt.plot(fpr, tpr, label=f'{title} (AUC={auc_roc:.2f})')
    plt.plot([0,1],[0,1],'k--')
    plt.xlabel("False Positive Rate"); plt.ylabel("True Positive Rate")
    plt.title(f"ROC Curve: {title}"); plt.legend(); plt.show()

    # PR
    plt.figure(figsize=(6,5))
    plt.plot(recall, precision, label=f'{title} (AUC={auc_pr:.2f})')
    plt.xlabel("Recall"); plt.ylabel("Precision")
    plt.title(f"Precision-Recall Curve: {title}"); plt.legend(); plt.show()

    # Score Distribution
    plt.figure(figsize=(7,5))
    sns.histplot(scores[y_true==0], color='green', bins=40, label='Normal', stat="density")
    sns.histplot(scores[y_true==1], color='red', bins=40, label='Anomaly', stat="density")
    plt.axvline(threshold, color='black', ls='--', label='Threshold')
    plt.legend(); plt.title(f"{title}: Score Distribution"); plt.show()

    return {"model": title, "auc_roc": auc_roc, "auc_pr": auc_pr, "f1": f1, "threshold": threshold}

# ----------------------------------------------------------
# 4️⃣ Isolation Forest
# ----------------------------------------------------------
iso = IsolationForest(
    contamination=len(y[y==1])/len(y),
    n_estimators=200,
    random_state=42
)
iso.fit(X_train)
scores_iso = -iso.decision_function(X_test)  # Higher = more abnormal
res_iso = evaluate_anomaly_model(y_test, scores_iso, title="Isolation Forest")

# ----------------------------------------------------------
# 5️⃣ One-Class SVM
# ----------------------------------------------------------
ocsvm = OneClassSVM(kernel='rbf', nu=0.05, gamma='scale')
ocsvm.fit(X_train[y_train==0])  # Train only on normal data
scores_svm = -ocsvm.decision_function(X_test)
res_svm = evaluate_anomaly_model(y_test, scores_svm, title="One-Class SVM")

# ----------------------------------------------------------
# 6️⃣ Autoencoder
# ----------------------------------------------------------
input_dim = X_train.shape[1]
encoding_dim = 5

autoencoder = keras.Sequential([
    layers.Input(shape=(input_dim,)),
    layers.Dense(8, activation='relu'),
    layers.Dense(encoding_dim, activation='relu'),
    layers.Dense(8, activation='relu'),
    layers.Dense(input_dim, activation='linear')
])

autoencoder.compile(optimizer='adam', loss='mse')
history = autoencoder.fit(
    X_train[y_train==0], X_train[y_train==0],
    epochs=40, batch_size=32, verbose=0, validation_split=0.1
)

plt.figure(figsize=(6,4))
plt.plot(history.history['loss'], label='Train')
plt.plot(history.history['val_loss'], label='Val')
plt.title("Autoencoder Training Loss"); plt.legend(); plt.show()

recon = autoencoder.predict(X_test)
mse = np.mean(np.square(X_test - recon), axis=1)
res_ae = evaluate_anomaly_model(y_test, mse, title="Autoencoder Reconstruction Error")

# ----------------------------------------------------------
# 7️⃣ Statistical Baselines
# ----------------------------------------------------------
# Z-Score
zscores = np.abs(zscore(X_test))
zs_mean = zscores.mean(axis=1)
res_z = evaluate_anomaly_model(y_test, zs_mean, title="Z-Score Baseline")

# Mahalanobis
cov = EmpiricalCovariance().fit(X_train[y_train==0])
mahal = np.array([cov.mahalanobis(x.reshape(1,-1)) for x in X_test])
res_mah = evaluate_anomaly_model(y_test, mahal, title="Mahalanobis Distance")

# ----------------------------------------------------------
# 8️⃣ PCA Projection (Fixed for Plotly)
# ----------------------------------------------------------
from sklearn.decomposition import PCA

pca = PCA(n_components=2)
X_proj = pca.fit_transform(X_test)

df_proj = pd.DataFrame(X_proj, columns=['PC1','PC2'])
df_proj['Anomaly'] = y_test

# Ensure positive normalized sizes
df_proj['Score_IF'] = np.maximum(0, scores_iso - scores_iso.min())
df_proj['Score_AE'] = np.maximum(0, mse - mse.min())

df_proj['Score_IF'] = df_proj['Score_IF'] / (df_proj['Score_IF'].max() + 1e-6) * 20 + 5
df_proj['Score_AE'] = df_proj['Score_AE'] / (df_proj['Score_AE'].max() + 1e-6) * 20 + 5

# Isolation Forest visualization
fig = px.scatter(
    df_proj, x='PC1', y='PC2', color='Anomaly',
    size='Score_IF', title='PCA Projection (size = IF score)',
    color_continuous_scale='RdYlGn_r'
)
fig.show()

# Autoencoder visualization
fig2 = px.scatter(
    df_proj, x='PC1', y='PC2', color='Anomaly',
    size='Score_AE', title='PCA Projection (size = AE recon error)',
    color_continuous_scale='RdYlGn_r'
)
fig2.show()

# ----------------------------------------------------------
# 9️⃣ Comparative Summary
# ----------------------------------------------------------
results = pd.DataFrame([res_iso, res_svm, res_ae, res_z, res_mah])
results = results[["model","auc_roc","auc_pr","f1","threshold"]]
display(results.sort_values("auc_roc", ascending=False).reset_index(drop=True))

plt.figure(figsize=(8,5))
sns.barplot(x="auc_roc", y="model", data=results, palette="coolwarm")
plt.title("Model Comparison by AUC-ROC"); plt.show()

plt.figure(figsize=(8,5))
sns.barplot(x="f1", y="model", data=results, palette="viridis")
plt.title("Model Comparison by F1"); plt.show()

# ----------------------------------------------------------
# 🔟 Threshold Tuning Visualization
# ----------------------------------------------------------
def plot_threshold_curve(y_true, scores, title="Threshold Tuning"):
    thresholds = np.linspace(scores.min(), scores.max(), 200)
    precisions, recalls, f1s = [], [], []
    for t in thresholds:
        y_pred = (scores > t).astype(int)
        cm = confusion_matrix(y_true, y_pred)
        tp, fp, fn = cm[1,1], cm[0,1], cm[1,0]
        prec = tp / (tp + fp + 1e-6)
        rec = tp / (tp + fn + 1e-6)
        f1 = 2*prec*rec / (prec + rec + 1e-6)
        precisions.append(prec); recalls.append(rec); f1s.append(f1)

    plt.figure(figsize=(7,5))
    plt.plot(thresholds, precisions, label='Precision')
    plt.plot(thresholds, recalls, label='Recall')
    plt.plot(thresholds, f1s, label='F1')
    plt.xlabel("Threshold"); plt.ylabel("Score"); plt.title(title)
    plt.legend(); plt.grid(True, alpha=0.3); plt.show()

plot_threshold_curve(y_test, scores_iso, "Isolation Forest Threshold Optimization")
plot_threshold_curve(y_test, mse, "Autoencoder Threshold Optimization")

print("\n✅ COMPLETE & FIXED: Isolation Forest, One-Class SVM, Autoencoder, Z-Score, Mahalanobis")