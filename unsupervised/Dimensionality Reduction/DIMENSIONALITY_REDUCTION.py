# ---- Variational Autoencoder (VAE) ----
class Sampling(tfl.Layer):
    def call(self, inputs):
        z_mean, z_log_var = inputs
        eps = tf.random.normal(shape=(tf.shape(z_mean)[0], tf.shape(z_mean)[1]))
        return z_mean + tf.exp(0.5 * z_log_var) * eps

# Encoder
vae_latent = 2
enc_in = tfk.Input(shape=(input_dim,))
eh = tfl.Dense(16, activation="relu")(enc_in)
eh = tfl.Dense(8, activation="relu")(eh)
z_mean = tfl.Dense(vae_latent)(eh)
z_log_var = tfl.Dense(vae_latent)(eh)
z_samp = Sampling()([z_mean, z_log_var])
ENC_VAE = tfk.Model(enc_in, [z_mean, z_log_var, z_samp], name="vae_encoder")

# Decoder
dec_in = tfk.Input(shape=(vae_latent,))
dh = tfl.Dense(8, activation="relu")(dec_in)
dh = tfl.Dense(16, activation="relu")(dh)
dec_out = tfl.Dense(input_dim, activation="linear")(dh)
DEC_VAE = tfk.Model(dec_in, dec_out, name="vae_decoder")

# VAE Model with custom train_step
class VAEModel(tfk.Model):
    def __init__(self, encoder, decoder, **kwargs):
        super().__init__(**kwargs)
        self.encoder = encoder
        self.decoder = decoder
        self.total_loss_tracker = tfk.metrics.Mean(name="loss")
        self.recon_loss_tracker = tfk.metrics.Mean(name="recon_loss")
        self.kl_loss_tracker = tfk.metrics.Mean(name="kl_loss")

    @property
    def metrics(self):
        return [self.total_loss_tracker, self.recon_loss_tracker, self.kl_loss_tracker]

    def train_step(self, data):
        if isinstance(data, tuple): data = data[0]
        with tf.GradientTape() as tape:
            z_mean, z_log_var, z = self.encoder(data, training=True)
            x_hat = self.decoder(z, training=True)
            recon_loss = tf.reduce_mean(tf.reduce_sum(tf.square(data - x_hat), axis=1))
            kl_loss = -0.5 * tf.reduce_mean(tf.reduce_sum(1 + z_log_var - tf.square(z_mean) - tf.exp(z_log_var), axis=1))
            total_loss = recon_loss + kl_loss
        grads = tape.gradient(total_loss, self.trainable_weights)
        self.optimizer.apply_gradients(zip(grads, self.trainable_weights))
        self.total_loss_tracker.update_state(total_loss)
        self.recon_loss_tracker.update_state(recon_loss)
        self.kl_loss_tracker.update_state(kl_loss)
        return {"loss": self.total_loss_tracker.result(),
                "recon_loss": self.recon_loss_tracker.result(),
                "kl_loss": self.kl_loss_tracker.result()}

    def test_step(self, data):
        if isinstance(data, tuple): data = data[0]
        z_mean, z_log_var, z = self.encoder(data, training=False)
        x_hat = self.decoder(z, training=False)
        recon_loss = tf.reduce_mean(tf.reduce_sum(tf.square(data - x_hat), axis=1))
        kl_loss = -0.5 * tf.reduce_mean(tf.reduce_sum(1 + z_log_var - tf.square(z_mean) - tf.exp(z_log_var), axis=1))
        total = recon_loss + kl_loss
        self.total_loss_tracker.update_state(total)
        self.recon_loss_tracker.update_state(recon_loss)
        self.kl_loss_tracker.update_state(kl_loss)
        return {"loss": self.total_loss_tracker.result(),
                "recon_loss": self.recon_loss_tracker.result(),
                "kl_loss": self.kl_loss_tracker.result()}

