def plot_2d(X2, labels=None, title="2D Projection"):
    plt.figure()
    if labels is None:
        plt.scatter(X2[:,0], X2[:,1], s=40)
    else:
        plt.scatter(X2[:,0], X2[:,1], c=labels, cmap="tab10", s=40)
    plt.title(title)
    plt.xlabel("Dim 1"); plt.ylabel("Dim 2")
    plt.show()

def scree_plot(pca, title="PCA Scree Plot"):
    plt.figure()
    plt.plot(np.cumsum(pca.explained_variance_ratio_), marker="o")
    plt.xlabel("Components")
    plt.ylabel("Cumulative Explained Variance")
    plt.title(title)
    plt.ylim(0, 1.05)
    plt.show()

def clustering_eval_on_embedding(emb2, y_true, tag):
    km = KMeans(n_clusters=len(np.unique(y_true)), random_state=RNG).fit(emb2)
    y_pred = km.labels_
    sil = silhouette_score(emb2, y_pred)
    ari = adjusted_rand_score(y_true, y_pred)
    nmi = normalized_mutual_info_score(y_true, y_pred)
    return {"method": tag, "silhouette": sil, "ari": ari, "nmi": nmi, "labels": y_pred}

def shepard_and_stress(X_high, X_low, title="MDS Shepard + Stress"):
    D_high = pairwise_distances(X_high)
    D_low  = pairwise_distances(X_low)
    idx = np.triu_indices_from(D_high, k=1)
    dh = D_high[idx]; dl = D_low[idx]
    stress = np.sqrt(((dh - dl)**2).sum() / (dh**2).sum())
    plt.figure()
    plt.scatter(dh, dl, s=10, alpha=0.6)
    plt.plot([dh.min(), dh.max()], [dh.min(), dh.max()], 'k--', linewidth=1)
    plt.xlabel("Original distances")
    plt.ylabel("Reduced distances")
    plt.title(f"{title} | Stress={stress:.4f}")
    plt.show()
    return float(stress)

def purity_score(y_true, y_pred):
    cm = confusion_matrix(y_true, y_pred)
    return np.sum(np.max(cm, axis=0)) / np.sum(cm)

def recon_error_linear(original, reconstructed, tag):
    mse = mean_squared_error(original, reconstructed)
    return {"method": tag, "reconstruction_mse": mse}

