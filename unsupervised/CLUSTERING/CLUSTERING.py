print("=== DBSCAN ===")
# Try a reasonable eps using k-distance heuristic (optional)
# Here: quick parameter sweep
eps_grid = np.linspace(0.2, 1.0, 9)
min_samples_grid = [3, 4, 5, 6, 8]
results = []
for eps in eps_grid:
    for ms in min_samples_grid:
        db = DBSCAN(eps=eps, min_samples=ms)
        labels = db.fit_predict(X)
        # skip all-noise or single cluster:
        if len(set(labels)) <= 1:
            sil = np.nan
        else:
            try:
                sil = silhouette_score(X, labels)
            except Exception:
                sil = np.nan
        results.append((eps, ms, len(set(labels)), np.sum(labels==-1), sil))
res_df = pd.DataFrame(results, columns=["eps", "min_samples", "n_clusters", "n_noise", "silhouette"])
print(res_df.sort_values("silhouette", ascending=False).head(10))

# Choose a decent combo (fallback to eps=0.5, ms=5 if NaN)
best = res_df.sort_values("silhouette", ascending=False).iloc[0]
eps_best, ms_best = float(best["eps"]), int(best["min_samples"])
if np.isnan(best["silhouette"]):
    eps_best, ms_best = 0.5, 5

dbscan = DBSCAN(eps=eps_best, min_samples=ms_best)
labels_db = dbscan.fit_predict(X)
