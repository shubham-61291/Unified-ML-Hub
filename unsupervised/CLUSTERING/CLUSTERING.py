def purity_score(y_true, y_pred):
    # Map each predicted cluster to the most common true label
    contingency = confusion_matrix(y_true, y_pred)
    return np.sum(np.max(contingency, axis=0)) / np.sum(contingency)

def dunn_index(X, labels):
    # Higher is better. Requires at least 2 clusters and no noise-only label.
    clusters = [X[labels == k] for k in np.unique(labels) if k != -1]
    if len(clusters) < 2:
        return np.nan
    # Intra-cluster diameter (max pairwise distance within cluster)
    def cluster_diameter(C):
        if len(C) < 2: return 0.0
        nbrs = NearestNeighbors(n_neighbors=len(C)).fit(C)
        dists = nbrs.kneighbors(C, n_neighbors=len(C), return_distance=True)[0]
        return np.max(dists)
    intra = np.max([cluster_diameter(C) for C in clusters])
    # Inter-cluster distance (min distance between pairs of clusters)
    def min_inter(Ci, Cj):
        # Approx via nearest neighbors
        nbrs = NearestNeighbors(n_neighbors=1).fit(Cj)
        dists, _ = nbrs.kneighbors(Ci)
        return np.min(dists)
    inter = np.min([min_inter(Ci, Cj) for Ci, Cj in combinations(clusters, 2)])
    if intra == 0: return np.nan
    return inter / intra

def gap_statistic(X, k_range, n_refs=10, random_state=42):
    # Tibshirani et al. Gap Statistic for KMeans
    rng = np.random.RandomState(random_state)
    shape = X.shape
    ref_disps = np.zeros((len(k_range), n_refs))
    gaps = np.zeros(len(k_range))
    sdk = np.zeros(len(k_range))
    wk = np.zeros(len(k_range))

    # bounds for uniform reference
    mins = X.min(axis=0)
    maxs = X.max(axis=0)

    for i, k in enumerate(k_range):
        # dispersion for actual data
        km = KMeans(n_clusters=k, n_init=10, random_state=rng)
        km.fit(X)
        wk[i] = np.log(km.inertia_)
        # reference datasets
        for j in range(n_refs):
            X_ref = rng.uniform(mins, maxs, size=shape)
            km_ref = KMeans(n_clusters=k, n_init=10, random_state=rng)
            km_ref.fit(X_ref)
            ref_disps[i, j] = np.log(km_ref.inertia_)
        gaps[i] = ref_disps[i].mean() - wk[i]
        sdk[i] = np.sqrt(((ref_disps[i] - ref_disps[i].mean())**2).sum() / n_refs) * np.sqrt(1 + 1/n_refs)
    return gaps, sdk, wk

def plot_2d(X2, labels, title="2D Plot"):
    plt.scatter(X2[:, 0], X2[:, 1], c=labels, s=30)
    plt.title(title)
    plt.xlabel("Component 1")
    plt.ylabel("Component 2")
    plt.show()

def plot_cluster_sizes(labels, title="Cluster Sizes"):
    counts = Counter(labels)
    keys = list(counts.keys())
    vals = [counts[k] for k in keys]
    plt.bar([str(k) for k in keys], vals)
    plt.title(title)
    plt.xlabel("Cluster Label")
    plt.ylabel("Count")
    plt.show()

def silhouette_details_plot(X, labels, title="Silhouette Plot"):
    # Detailed silhouette plot à la scikit-learn example
    from sklearn.metrics import silhouette_samples
    unique = [u for u in np.unique(labels) if u != -1]
    if len(unique) < 2:
        print("Silhouette plot needs >= 2 clusters (excluding noise).")
        return
    sil_avg = silhouette_score(X, labels)
    sample_sil = silhouette_samples(X, labels)
    y_lower = 10
    plt.figure()
    for i, c in enumerate(unique):
        ith = sample_sil[labels == c]
        ith.sort()
        size_c = ith.shape[0]
        y_upper = y_lower + size_c
        plt.fill_betweenx(np.arange(y_lower, y_upper), 0, ith)
        plt.text(-0.05, y_lower + 0.5 * size_c, str(c))
        y_lower = y_upper + 10
    plt.axvline(x=sil_avg, linestyle="--")
    plt.title(f"{title} (avg={sil_avg:.3f})")
    plt.xlabel("Silhouette coefficient")
    plt.ylabel("Cluster label")
    plt.show()

def evaluate_all(X, labels, algo_name, y_true=None, show_sil_plot=True):
    # Internal
    try:
        sil = silhouette_score(X, labels)
    except Exception:
        sil = np.nan
    try:
        db  = davies_bouldin_score(X, labels)
    except Exception:
        db = np.nan
    try:
        ch  = calinski_harabasz_score(X, labels)
    except Exception:
        ch = np.nan
    di = dunn_index(X, labels)

    print(f"🔹 {algo_name} — Internal Metrics")
    print(f"Silhouette: {sil:.3f} | DB-Index: {db:.3f} | CH-Index: {ch:.1f} | Dunn: {di if isinstance(di, float) else np.nan:.3f}")
    if show_sil_plot:
        silhouette_details_plot(X, labels, f"Silhouette — {algo_name}")

    # External (if labels available)
    if y_true is not None:
        try:
            ari = adjusted_rand_score(y_true, labels)
            nmi = normalized_mutual_info_score(y_true, labels)
            vms = v_measure_score(y_true, labels)
            hom = homogeneity_score(y_true, labels)
            com = completeness_score(y_true, labels)
            fmi = fowlkes_mallows_score(y_true, labels)
            pur = purity_score(y_true, labels)
            print(f"🔸 {algo_name} — External Metrics (need ground truth)")
            print(f"ARI: {ari:.3f} | NMI: {nmi:.3f} | V-Measure: {vms:.3f} | Hom: {hom:.3f} | Comp: {com:.3f} | FMI: {fmi:.3f} | Purity: {pur:.3f}")
            # Confusion-style heatmap
            cm = confusion_matrix(y_true, labels)
            plt.imshow(cm, aspect='auto')
            plt.title(f"Confusion Heatmap — {algo_name}")
            plt.xlabel("Pred Cluster"); plt.ylabel("True Label")
            plt.colorbar()
            plt.show()
        except Exception as e:
            print("External metrics error:", e)

    # Cluster sizes
    plot_cluster_sizes(labels, f"Cluster Sizes — {algo_name}")

    # PCA & t-SNE visualizations
    plot_2d(X_pca2, labels, f"PCA (2D) — {algo_name}")
    plot_2d(X_tsne2, labels, f"t-SNE (2D) — {algo_name}")


