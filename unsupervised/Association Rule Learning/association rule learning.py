def rules_scatter(rules, title="Rules: Support vs Confidence (size=Lift)"):
    plt.figure(figsize=(7,5))
    plt.scatter(rules["support"], rules["confidence"], s=200*rules["lift"].clip(0,3), alpha=0.6)
