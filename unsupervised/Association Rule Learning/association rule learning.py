# 2) FREQUENT ITEMSETS: Apriori / FP-Growth
# ------------------------------------------------------------------------------
def mine_itemsets(df, algo="apriori", min_support=0.02, use_colnames=True, max_len=None):
    if algo == "apriori":
        fi = apriori(df, min_support=min_support, use_colnames=use_colnames, max_len=max_len)
    elif algo == "fpgrowth":
        fi = fpgrowth(df, min_support=min_support, use_colnames=use_colnames, max_len=max_len)
    else:
        raise ValueError("algo must be 'apriori' or 'fpgrowth'")
    fi.sort_values(["support","itemsets"], ascending=[False, True], inplace=True)
    fi.reset_index(drop=True, inplace=True)
    return fi

# ------------------------------------------------------------------------------
# 3) ECLAT (vertical format) — clean reference implementation
# ------------------------------------------------------------------------------
def build_vertical_format(transactions):
    tidsets = defaultdict(set)  # item -> set of TIDs
    for tid, basket in enumerate(transactions):
        for item in basket:
            tidsets[frozenset([item])].add(tid)
    return tidsets, len(transactions)

def eclat_recursive(prefix, items_tidsets, min_support_count, results):
    items = list(items_tidsets.items())
    for i in range(len(items)):
        itemset, tidset = items[i]
        new_itemset = prefix | itemset
        support_count = len(tidset)
        if support_count >= min_support_count:
            results.append((new_itemset, support_count))
            # Build extensions
            exts = {}
            for j in range(i+1, len(items)):
                item2, tidset2 = items[j]
                inter = tidset & tidset2
                if len(inter) >= min_support_count:
                    exts[item2] = inter
            if exts:
                eclat_recursive(new_itemset, exts, min_support_count, results)

def eclat(transactions, min_support=0.02, max_len=None):
    tidsets, n_tx = build_vertical_format(transactions)
    min_count = int(np.ceil(min_support * n_tx))
    results = []
    # start from singletons
    eclat_recursive(frozenset(), tidsets, min_count, results)
    # convert results to DataFrame like mlxtend's frequent itemsets
    rows = []
    for iset, cnt in results:
        if max_len is not None and len(iset) > max_len:
            continue
        rows.append({"support": cnt / n_tx, "itemsets": iset})
    fi = pd.DataFrame(rows).drop_duplicates().sort_values(
        ["support","itemsets"], ascending=[False, True]).reset_index(drop=True)
    return fi

# ------------------------------------------------------------------------------
# 4) ASSOCIATION RULES + METRICS (support, confidence, lift, leverage, conviction, jaccard, kulczynski)
# ------------------------------------------------------------------------------
def rules_from_itemsets(fi, df, metric="confidence", min_threshold=0.5):
    # Use mlxtend association_rules for base metrics
    rules = association_rules(fi, metric=metric, min_threshold=min_threshold)
    # Add Jaccard & Kulczynski (two-way balance)
    def jaccard(row):
        # row['support'] is support(X∪Y)
        sup_x = row['support'] * 1.0 / row['confidence']  # support(X) = sup(XY)/conf
        sup_y = row['lift'] * sup_x * 0 + row['support'] / row['confidence'] * 0  # not useful here
        # Better compute supports directly to avoid rounding; we can recompute both from df.
        return np.nan  # We'll compute below with exact supports.

    # Exact supports for antecedent and consequent
    def support_of(itemset):
        cols = list(itemset)
        return df[cols].all(axis=1).mean() if len(cols)>0 else 0.0

    # Add exact supports (antecedent, consequent)
    rules["support_x"] = rules["antecedents"].apply(lambda s: support_of(list(s)))
    rules["support_y"] = rules["consequents"].apply(lambda s: support_of(list(s)))

    # Derived metrics
    # leverage = supp(X∪Y) - supp(X)*supp(Y)
    rules["leverage"] = rules["support"] - rules["support_x"] * rules["support_y"]
    # conviction = (1 - supp(Y)) / (1 - conf(X→Y))
    rules["conviction"] = (1 - rules["support_y"]) / (1 - rules["confidence"]).replace(0, np.nan)
    # jaccard = supp(X∪Y) / (supp(X)+supp(Y)-supp(X∪Y))
    denom = (rules["support_x"] + rules["support_y"] - rules["support"])
    rules["jaccard"] = rules["support"] / denom.replace(0, np.nan)
    # kulczynski = 0.5 * ( conf(X→Y) + conf(Y→X) )
    # conf(Y→X) = supp(X∪Y) / supp(Y)
    rules["conf_y_to_x"] = rules["support"] / rules["support_y"].replace(0, np.nan)
    rules["kulczynski"] = 0.5 * (rules["confidence"] + rules["conf_y_to_x"])
    return rules

# ------------------------------------------------------------------------------
# 5) REDUNDANCY PRUNING (remove rules whose consequents are same and antecedent is a superset of another with >= metrics)
# ------------------------------------------------------------------------------
def prune_redundant_rules(rules):
    # Simple redundancy: If A1 -> C and A2 -> C with A1 ⊂ A2 AND conf(A1->C) >= conf(A2->C), drop A2.
    rules = rules.copy()
    rules["ante_len"] = rules["antecedents"].apply(len)
    rules.sort_values(["consequents","ante_len","confidence"], ascending=[True, True, False], inplace=True)

    to_drop = set()
    grouped = rules.groupby("consequents")
    for cons, grp in grouped:
        seen = []
        for idx, row in grp.iterrows():
            A = set(row["antecedents"])
            confA = row["confidence"]
            # compare against previously seen smaller antecedents for same consequent
            for jdx in seen:
                Aj = set(rules.loc[jdx, "antecedents"])
                confAj = rules.loc[jdx, "confidence"]
                if Aj.issubset(A) and confAj >= confA:
                    to_drop.add(idx)
                    break
            if idx not in to_drop:
                seen.append(idx)
    return rules.drop(index=list(to_drop)).reset_index(drop=True)

