def top_item_bars(rules, topn=15):
    ant = Counter(chain.from_iterable([list(s) for s in rules["antecedents"]]))
    con = Counter(chain.from_iterable([list(s) for s in rules["consequents"]]))
    fig, axes = plt.subplots(1,2, figsize=(12,4))
    a = pd.Series(ant).sort_values(ascending=False).head(topn)
    c = pd.Series(con).sort_values(ascending=False).head(topn)
