# Larger synthetic generator (co-occurrence structure baked in)
def generate_synthetic_transactions(n=2000, p_noise=0.1, rng=RNG):
    rng = np.random.default_rng(rng)
    catalog = ["bread","butter","milk","eggs","jam","cheese","cereal","yogurt",
               "cookies","juice","tea","coffee","pasta","sauce","rice","beans"]
    base_probs = {it: rng.uniform(0.05, 0.35) for it in catalog}

    # Inject some meaningful associations
    # bread -> butter, milk; pasta -> sauce; rice -> beans; tea -> cookies; coffee -> cookies
    boosts = {
        ("bread","butter"): 0.30, ("bread","milk"):0.20,
        ("pasta","sauce"):0.40, ("rice","beans"):0.35,
        ("tea","cookies"):0.25, ("coffee","cookies"):0.25,
        ("cheese","bread"):0.15, ("yogurt","cereal"):0.22
    }

    tx = []
    for _ in range(n):
        basket = []
        # base picks
        for it in catalog:
            if rng.random() < base_probs[it]:
                basket.append(it)
        # inject associations if antecedent present
        for (a,b), delta in boosts.items():
            if a in basket and rng.random() < delta:
                basket.append(b)
        # add noise items
        for it in catalog:
            if rng.random() < p_noise*0.02:
                basket.append(it)
        # deduplicate within basket
        basket = sorted(list(set(basket)))
        # don't allow empty baskets (rare but possible)
        if not basket:
            basket = [rng.choice(catalog)]
        tx.append(basket)
    return tx

