# 6) TRAIN/TEST SPLIT for Generalization Check
# ------------------------------------------------------------------------------
def train_test_rules(transactions, test_frac=0.25, algo="apriori", min_support=0.02, min_conf=0.5, max_len=None):
    n = len(transactions)
    idx = np.random.permutation(n)
    cut = int((1 - test_frac) * n)
    train_tx = [transactions[i] for i in idx[:cut]]
    test_tx  = [transactions[i] for i in idx[cut:]]

    df_tr = transactions_to_df(train_tx)
    df_te = transactions_to_df(test_tx)

    # frequent itemsets
    if algo == "eclat":
        fi = eclat(train_tx, min_support=min_support, max_len=max_len)
    else:
        fi = mine_itemsets(df_tr, algo=algo, min_support=min_support, max_len=max_len)

    # rules and metrics on TRAIN
    rules_tr = rules_from_itemsets(fi, df_tr, metric="confidence", min_threshold=min_conf)

    # Evaluate confidence/lift on TEST for the same (X->Y)
    def support_df(df, items):
        if len(items)==0: return 0.0
        return df[list(items)].all(axis=1).mean()

    def conf_on_df(df, X, Y):
        supX = support_df(df, X)
        if supX == 0: return np.nan
        supXY = support_df(df, set(X)|set(Y))
        return supXY / supX

    def lift_on_df(df, X, Y):
        conf = conf_on_df(df, X, Y)
        supY = support_df(df, Y)
        if supY == 0 or not isfinite(conf): return np.nan
        return conf / supY

    rules_tr["test_confidence"] = rules_tr.apply(lambda r: conf_on_df(df_te, r["antecedents"], r["consequents"]), axis=1)
    rules_tr["test_lift"] = rules_tr.apply(lambda r: lift_on_df(df_te, r["antecedents"], r["consequents"]), axis=1)

    return rules_tr, fi, (df_tr, df_te)

