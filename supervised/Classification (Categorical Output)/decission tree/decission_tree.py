import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

from sklearn.datasets import load_breast_cancer, load_iris, make_multilabel_classification
from sklearn.model_selection import train_test_split, StratifiedKFold, cross_validate, cross_val_predict
from sklearn.tree import DecisionTreeClassifier, plot_tree
from sklearn.preprocessing import StandardScaler
from sklearn.multiclass import OneVsRestClassifier
from sklearn.metrics import (
    confusion_matrix, classification_report, roc_curve, auc,
    precision_recall_curve, average_precision_score, log_loss,
    brier_score_loss, matthews_corrcoef, roc_auc_score, f1_score,
    hamming_loss, jaccard_score
)
from sklearn.calibration import CalibrationDisplay

sns.set(style="whitegrid", rc={"figure.figsize": (8,6)})

RANDOM_STATE = 42

# ------------------------------
# Helpers
# ------------------------------
def cm_heatmap(cm, title, cmap="Blues"):
    sns.heatmap(cm, annot=True, fmt="d", cmap=cmap)
    plt.title(title); plt.xlabel("Predicted"); plt.ylabel("Actual"); plt.show()

def plot_curves_with_thresholds_binary(y_true, y_prob, title="", mark_thresholds=None):
    fpr, tpr, thr_roc = roc_curve(y_true, y_prob)
    precision, recall, thr_pr = precision_recall_curve(y_true, y_prob)
    avg_prec = average_precision_score(y_true, y_prob)
    roc_auc = auc(fpr, tpr)

    fig, axs = plt.subplots(1,2, figsize=(14,6))

    # ROC
    axs[0].plot(fpr, tpr, label=f"AUC={roc_auc:.3f}")
    axs[0].plot([0,1],[0,1],'k--', lw=1)
    axs[0].set_title(f"ROC Curve - {title}")
    axs[0].set_xlabel("False Positive Rate")
    axs[0].set_ylabel("True Positive Rate")
    axs[0].legend()
    # annotate thresholds sparsely
    for i in range(0, len(thr_roc), max(1, len(thr_roc)//10)):
        axs[0].annotate(f"{thr_roc[i]:.2f}", (fpr[i], tpr[i]))

    # PR
    axs[1].plot(recall, precision, label=f"AP={avg_prec:.3f}")
    axs[1].set_title(f"PR Curve - {title}")
    axs[1].set_xlabel("Recall")
    axs[1].set_ylabel("Precision")
    axs[1].legend()
    for i in range(0, len(thr_pr), max(1, len(thr_pr)//10)):
        idx = i
        axs[1].annotate(f"{thr_pr[i]:.2f}", (recall[idx], precision[idx]))

    # Mark chosen thresholds
    if mark_thresholds:
        for t in mark_thresholds:
            # nearest on ROC
            idx_r = np.argmin(np.abs(thr_roc - t))
            axs[0].scatter(fpr[idx_r], tpr[idx_r], s=80, edgecolor='k', zorder=3)
            axs[0].annotate(f"t={t:.2f}", (fpr[idx_r], tpr[idx_r]))
            # nearest on PR
            if len(thr_pr) > 0:
                idx_p = np.argmin(np.abs(thr_pr - t))
                axs[1].scatter(recall[idx_p], precision[idx_p], s=80, edgecolor='k', zorder=3)
                axs[1].annotate(f"t={t:.2f}", (recall[idx_p], precision[idx_p]))

    plt.show()

def plot_feature_importance(importances, feature_names, title="Feature Importance", top_k=None, cmap="viridis"):
    imp = np.array(importances)
    names = np.array(feature_names)
    if top_k is not None and top_k < len(imp):
        idx = np.argsort(imp)[::-1][:top_k]
        imp, names = imp[idx], names[idx]
    order = np.argsort(imp)
    plt.figure(figsize=(8, max(5, len(imp)*0.3)))
    plt.barh(names[order], imp[order])
    plt.title(title)
    plt.xlabel("Importance")
    plt.show()

