cm = confusion_matrix(y_test, y_pred)
cm_heatmap(cm, "Confusion Matrix — Multiclass (Decision Tree)", cmap="Greens")

# OvR ROC curves per class
plt.figure(figsize=(8,6))
for i in range(len(class_names)):
    fpr, tpr, _ = roc_curve((y_test==i).astype(int), y_prob[:,i])
    plt.plot(fpr, tpr, label=f"{class_names[i]} (AUC={auc(fpr,tpr):.3f})")
plt.plot([0,1],[0,1],'k--', lw=1)
plt.title("ROC Curves — Multiclass (OvR) — Decision Tree")
plt.xlabel("FPR"); plt.ylabel("TPR"); plt.legend(); plt.show()

# OvR PR curves per class
plt.figure(figsize=(8,6))
for i in range(len(class_names)):
    precision, recall, _ = precision_recall_curve((y_test==i).astype(int), y_prob[:,i])
    ap = average_precision_score((y_test==i).astype(int), y_prob[:,i])
    plt.plot(recall, precision, label=f"{class_names[i]} (AP={ap:.3f})")
plt.title("PR Curves — Multiclass (OvR) — Decision Tree")
plt.xlabel("Recall"); plt.ylabel("Precision"); plt.legend(); plt.show()

# Feature importance
plot_feature_importance(tree_multi.feature_importances_, feature_names, title="Feature Importance — Multiclass (Decision Tree)")

# Tree visualization (cap depth for readability)
plt.figure(figsize=(16,8))
plot_tree(tree_multi, feature_names=feature_names, class_names=class_names, filled=True, max_depth=3, fontsize=8)
plt.title("Decision Tree Structure — Multiclass (Depth<=3)")
