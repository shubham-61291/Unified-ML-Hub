# 3) MULTILABEL — Synthetic (OvR)
# ==========================================================
print("\n=== Multilabel: Decision Tree (One-vs-Rest) on Synthetic ===")
X, y = make_multilabel_classification(n_samples=1200, n_features=25, n_classes=6, n_labels=2, random_state=RANDOM_STATE)

ovr_tree = OneVsRestClassifier(DecisionTreeClassifier(random_state=RANDOM_STATE))

# Cross-validated predictions for multilabel metrics
y_pred = cross_val_predict(ovr_tree, X, y, cv=5)

print("\nClassification Report (Multilabel):\n", classification_report(y, y_pred, zero_division=0))
print("Subset Accuracy:", (y == y_pred).all(axis=1).mean())
print("Hamming Loss:", hamming_loss(y, y_pred))
print("Jaccard (Micro):", jaccard_score(y, y_pred, average="micro"))

# Fit on full data to extract importances (mean across label-estimators)
ovr_tree.fit(X, y)
importances_list = []
for est in ovr_tree.estimators_:
    importances_list.append(est.feature_importances_)
importances_mean = np.mean(importances_list, axis=0)

plot_feature_importance(importances_mean, [f"f{i}" for i in range(X.shape[1])],
                        title="Feature Importance — Multilabel (Mean across labels)", top_k=20, cmap="magma")

