cv_results = cross_validate(rf_multi, X, y, cv=cv, scoring=scoring)
print("\nCross-Validation (Multiclass, 5-fold):")
for k in scoring.keys():
    vals = cv_results[f"test_{k}"]
    print(f"{k:>12}: {vals.mean():.4f} ± {vals.std():.4f}")

# Single split for confusion + OvR ROC/PR + importances
X_train, X_test, y_train, y_test = train_test_split(X, y, stratify=y, test_size=0.3, random_state=RANDOM_STATE)
rf_multi.fit(X_train, y_train)
y_pred = rf_multi.predict(X_test)
y_prob = rf_multi.predict_proba(X_test)

print("\nClassification Report (Multiclass):\n", classification_report(y_test, y_pred, zero_division=0))

cm = confusion_matrix(y_test, y_pred)
cm_heatmap(cm, "Confusion Matrix — Multiclass (Random Forest)", cmap="Greens")

# OvR ROC per class
plt.figure(figsize=(8,6))
for i in range(len(class_names)):
    fpr, tpr, _ = roc_curve((y_test==i).astype(int), y_prob[:,i])
    plt.plot(fpr, tpr, label=f"{class_names[i]} (AUC={auc(fpr,tpr):.3f})")
plt.plot([0,1],[0,1],'k--', lw=1)
plt.title("ROC Curves — Multiclass (OvR) — Random Forest")
plt.xlabel("FPR"); plt.ylabel("TPR"); plt.legend(); plt.show()

# OvR PR per class
plt.figure(figsize=(8,6))
for i in range(len(class_names)):
    precision, recall, _ = precision_recall_curve((y_test==i).astype(int), y_prob[:,i])
    ap = average_precision_score((y_test==i).astype(int), y_prob[:,i])
    plt.plot(recall, precision, label=f"{class_names[i]} (AP={ap:.3f})")
plt.title("PR Curves — Multiclass (OvR) — Random Forest")
plt.xlabel("Recall"); plt.ylabel("Precision"); plt.legend(); plt.show()

# Importances (MDI) + permutation
plot_feature_importance(rf_multi.feature_importances_, feature_names, title="Feature Importance (MDI) — Multiclass", top_k=10)
plot_perm_importance(rf_multi, X_test, y_test, feature_names, title="Permutation Importance — Multiclass", top_k=10, n_repeats=10)

