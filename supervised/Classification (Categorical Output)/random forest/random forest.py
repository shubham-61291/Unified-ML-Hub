# 1) BINARY — Breast Cancer (Random Forest)
# ==========================================================
print("\n=== Binary: Random Forest on Breast Cancer ===")
breast = load_breast_cancer()
X, y = breast.data, breast.target
feature_names = breast.feature_names

rf_bin = RandomForestClassifier(
    n_estimators=500, max_depth=None, random_state=RANDOM_STATE,
    n_jobs=-1, oob_score=True, bootstrap=True
)

# ----- 5-fold CV (stable metrics)
cv = StratifiedKFold(n_splits=5, shuffle=True, random_state=RANDOM_STATE)
scoring = {
    "accuracy": "accuracy",
    "precision": "precision",
    "recall": "recall",
    "f1": "f1",
    "roc_auc": "roc_auc",
    "neg_log_loss": "neg_log_loss"
}
cv_results = cross_validate(rf_bin, X, y, cv=cv, scoring=scoring, return_estimator=False)
print("\nCross-Validation (Binary, 5-fold):")
for k in scoring.keys():
    vals = cv_results[f"test_{k}"]
    print(f"{k:>12}: {vals.mean():.4f} ± {vals.std():.4f}")

# ----- Train/Test for detailed eval + plots + threshold tuning
X_train, X_test, y_train, y_test = train_test_split(X, y, stratify=y, test_size=0.3, random_state=RANDOM_STATE)
rf_bin.fit(X_train, y_train)

print("\nOOB Score (trained on train set):", round(rf_bin.oob_score_, 6))

y_pred = rf_bin.predict(X_test)
y_prob = rf_bin.predict_proba(X_test)[:,1]

print("\nClassification Report (Binary):\n", classification_report(y_test, y_pred, zero_division=0))
print("Log Loss:", round(log_loss(y_test, y_prob), 6))
print("Brier Score:", round(brier_score_loss(y_test, y_prob), 6))
print("MCC:", round(matthews_corrcoef(y_test, y_pred), 6))

cm = confusion_matrix(y_test, y_pred)
cm_heatmap(cm, "Confusion Matrix — Binary (Random Forest)")

# ROC/PR with thresholds annotated
roc_pr_with_thresholds_binary(y_test, y_prob, title="Random Forest (Binary)")

# Calibration curve
CalibrationDisplay.from_predictions(y_test, y_prob, n_bins=10)
plt.title("Calibration Curve — Binary (Random Forest)")
plt.show()

# Feature importance (MDI)
plot_feature_importance(rf_bin.feature_importances_, feature_names, title="Feature Importance (MDI) — Binary", top_k=20)

# Permutation importance on test
plot_perm_importance(rf_bin, X_test, y_test, feature_names, title="Permutation Importance — Binary", top_k=15, n_repeats=10)

# OOB curve vs n_estimators
n_list = [10, 50, 100, 200, 300, 400, 500]
oob_scores = []
for n in n_list:
    rf_tmp = RandomForestClassifier(
        n_estimators=n, random_state=RANDOM_STATE, n_jobs=-1, oob_score=True, bootstrap=True
    )
    rf_tmp.fit(X_train, y_train)
    oob_scores.append(rf_tmp.oob_score_)
plt.figure(figsize=(8,5))
plt.plot(n_list, oob_scores, marker='o')
plt.title("OOB Score vs Number of Trees (Binary)")
plt.xlabel("# Trees"); plt.ylabel("OOB Score")
plt.show()

# ----- Threshold tuning + optimal thresholds table
thresholds = np.linspace(0, 1, 1001)
precisions, recalls, f1s, j_stats, costs, fprs, tprs, tps, fps, fns, tns = ([] for _ in range(11))
C_FP, C_FN = 1, 10  # example business costs

for t in thresholds:
    preds = (y_prob >= t).astype(int)
    TP = np.sum((preds==1) & (y_test==1))
    FP = np.sum((preds==1) & (y_test==0))
    FN = np.sum((preds==0) & (y_test==1))
    TN = np.sum((preds==0) & (y_test==0))

    p = TP/(TP+FP) if (TP+FP)>0 else 0.0
    r = TP/(TP+FN) if (TP+FN)>0 else 0.0
    f1 = f1_score(y_test, preds, zero_division=0)
    tpr = r
    fpr = FP/(FP+TN) if (FP+TN)>0 else 0.0
    j = tpr - fpr
    cost = FP*C_FP + FN*C_FN

    precisions.append(p); recalls.append(r); f1s.append(f1); j_stats.append(j); costs.append(cost)
    fprs.append(fpr); tprs.append(tpr)
    tps.append(TP); fps.append(FP); fns.append(FN); tns.append(TN)

precisions = np.array(precisions); recalls = np.array(recalls)
f1s = np.array(f1s); j_stats = np.array(j_stats); costs = np.array(costs)
fprs = np.array(fprs); tprs = np.array(tprs)
tps = np.array(tps); fps = np.array(fps); fns = np.array(fns); tns = np.array(tns)

idx_f1 = np.argmax(f1s)
idx_j  = np.argmax(j_stats)
idx_c  = np.argmin(costs)

opt_table = pd.DataFrame([
    ["F1-max", thresholds[idx_f1], precisions[idx_f1], recalls[idx_f1], f1s[idx_f1], j_stats[idx_f1],
     costs[idx_f1], fprs[idx_f1], tprs[idx_f1], int(tps[idx_f1]), int(fps[idx_f1]), int(fns[idx_f1]), int(tns[idx_f1])],
    ["J-max", thresholds[idx_j], precisions[idx_j], recalls[idx_j], f1s[idx_j], j_stats[idx_j],
     costs[idx_j], fprs[idx_j], tprs[idx_j], int(tps[idx_j]), int(fps[idx_j]), int(fns[idx_j]), int(tns[idx_j])],
    ["Cost-min", thresholds[idx_c], precisions[idx_c], recalls[idx_c], f1s[idx_c], j_stats[idx_c],
     costs[idx_c], fprs[idx_c], tprs[idx_c], int(tps[idx_c]), int(fps[idx_c]), int(fns[idx_c]), int(tns[idx_c])]
], columns=["Criterion","Threshold","Precision","Recall","F1","Youden_J","Cost","FPR","TPR","TP","FP","FN","TN"])

print("\nOptimal Thresholds — Binary (Random Forest)")
print(opt_table.to_string(index=False, float_format=lambda x: f"{x:.3f}" if isinstance(x,float) else str(x)))

plt.figure(figsize=(12,6))
plt.plot(thresholds, precisions, label="Precision")
plt.plot(thresholds, recalls, label="Recall")
plt.plot(thresholds, f1s, label="F1")
plt.plot(thresholds, j_stats, label="Youden's J")
plt.plot(thresholds, costs, label=f"Cost (C_FN={C_FN}, C_FP={C_FP})")
for idx, name in [(idx_f1,"F1-max"), (idx_j,"J-max"), (idx_c,"Cost-min")]:
    t = thresholds[idx]
    plt.scatter([t],[f1s[idx]], s=80, edgecolor='k', label=f"{name} (t={t:.3f})")
plt.axvline(0.5, color='k', linestyle='--', lw=1, label="Default t=0.5")
plt.xlabel("Threshold"); plt.ylabel("Score / Cost")
plt.title("Threshold Tuning — Random Forest (Binary)")
plt.legend(); plt.show()

roc_pr_with_thresholds_binary(y_test, y_prob, title="Random Forest (Binary) — Optima Marked",
                              mark_thresholds=[thresholds[idx_f1], thresholds[idx_j], thresholds[idx_c]])

