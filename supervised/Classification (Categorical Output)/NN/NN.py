import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
from sklearn.datasets import load_breast_cancer, load_iris, make_multilabel_classification
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from sklearn.metrics import (confusion_matrix, classification_report,
                             roc_curve, auc, precision_recall_curve,
                             average_precision_score, log_loss,
                             brier_score_loss, matthews_corrcoef,
                             hamming_loss, jaccard_score)

import tensorflow as tf
from tensorflow.keras import models, layers

sns.set(style="whitegrid", rc={"figure.figsize": (8,6)})
RANDOM_STATE = 42

# -----------------------
# Helper functions
# -----------------------
def plot_confusion(cm, title, labels):
    plt.figure(figsize=(6,5))
    sns.heatmap(cm, annot=True, fmt="d", cmap="Blues",
                xticklabels=labels, yticklabels=labels)
    plt.title(title); plt.xlabel("Predicted"); plt.ylabel("Actual")
    plt.show()

def plot_learning_curves(history, title="Learning Curves"):
    plt.figure(figsize=(8,5))
    plt.plot(history.history['loss'], label="Train Loss")
    plt.plot(history.history['val_loss'], label="Val Loss")
    if 'accuracy' in history.history:
        plt.plot(history.history['accuracy'], label="Train Acc")
        plt.plot(history.history['val_accuracy'], label="Val Acc")
    plt.title(title); plt.legend(); plt.show()

def plot_roc_pr(y_true, y_prob, title=""):
    fpr, tpr, thr_roc = roc_curve(y_true, y_prob)
    precision, recall, thr_pr = precision_recall_curve(y_true, y_prob)
    roc_auc = auc(fpr, tpr)
    ap = average_precision_score(y_true, y_prob)

    fig, axs = plt.subplots(1,2, figsize=(14,6))
    axs[0].plot(fpr, tpr, label=f"AUC={roc_auc:.3f}")
    axs[0].plot([0,1],[0,1],'k--')
    axs[0].set_title(f"ROC Curve — {title}"); axs[0].legend()
    for i in np.linspace(0, len(thr_roc)-1, 5, dtype=int):
        axs[0].annotate(f"{thr_roc[i]:.2f}", (fpr[i], tpr[i]))

    axs[1].plot(recall, precision, label=f"AP={ap:.3f}")
    axs[1].set_title(f"PR Curve — {title}"); axs[1].legend()
    for i in np.linspace(0, len(thr_pr)-1, 5, dtype=int):
        axs[1].annotate(f"{thr_pr[i]:.2f}", (recall[i], precision[i]))
    plt.show()

# ==========================================================
# 1) BINARY — Breast Cancer Dataset
# ==========================================================
print("\n=== Binary Neural Net ===")
data = load_breast_cancer()
X, y = data.data, data.target
X = StandardScaler().fit_transform(X)

X_train, X_test, y_train, y_test = train_test_split(
    X, y, stratify=y, test_size=0.3, random_state=RANDOM_STATE)

model_bin = models.Sequential([
    layers.Input(shape=(X.shape[1],)),   # ✅ FIXED
    layers.Dense(32, activation="relu"),
    layers.Dropout(0.3),
    layers.Dense(16, activation="relu"),
    layers.Dense(1, activation="sigmoid")
])
model_bin.compile(optimizer="adam",
                  loss="binary_crossentropy",
                  metrics=["accuracy"])

hist_bin = model_bin.fit(X_train, y_train, validation_data=(X_test, y_test),
                         epochs=30, batch_size=32, verbose=0)

plot_learning_curves(hist_bin, "Binary — Learning Curves")

y_prob = model_bin.predict(X_test).ravel()
y_pred = (y_prob>=0.5).astype(int)

print(classification_report(y_test, y_pred))
print("Log Loss:", log_loss(y_test, y_prob))
print("Brier Score:", brier_score_loss(y_test, y_prob))
print("MCC:", matthews_corrcoef(y_test, y_pred))

cm = confusion_matrix(y_test, y_pred)
plot_confusion(cm, "Confusion Matrix — Binary", data.target_names)

plot_roc_pr(y_test, y_prob, "Binary NN")

# ==========================================================
# 2) MULTICLASS — Iris Dataset
# ==========================================================
print("\n=== Multiclass Neural Net ===")
iris = load_iris()
X, y = iris.data, iris.target
X = StandardScaler().fit_transform(X)
y_cat = tf.keras.utils.to_categorical(y)

X_train, X_test, y_train, y_test = train_test_split(
    X, y_cat, stratify=y, test_size=0.3, random_state=RANDOM_STATE)

model_multi = models.Sequential([
    layers.Input(shape=(X.shape[1],)),   # ✅ FIXED
    layers.Dense(32, activation="relu"),
    layers.Dropout(0.3),
    layers.Dense(16, activation="relu"),
    layers.Dense(y_cat.shape[1], activation="softmax")
])
model_multi.compile(optimizer="adam",
                    loss="categorical_crossentropy",
                    metrics=["accuracy"])

hist_multi = model_multi.fit(X_train, y_train, validation_data=(X_test, y_test),
                             epochs=40, batch_size=16, verbose=0)

plot_learning_curves(hist_multi, "Multiclass — Learning Curves")

y_prob = model_multi.predict(X_test)
y_pred = np.argmax(y_prob, axis=1)
y_true = np.argmax(y_test, axis=1)

print(classification_report(y_true, y_pred, target_names=iris.target_names))

cm = confusion_matrix(y_true, y_pred)
plot_confusion(cm, "Confusion Matrix — Multiclass", iris.target_names)

# OvR ROC/PR curves
for i, cname in enumerate(iris.target_names):
    y_bin = (y_true==i).astype(int)
    plot_roc_pr(y_bin, y_prob[:,i], f"Class {cname}")

# ==========================================================
# 3) MULTILABEL — Synthetic Dataset
# ==========================================================
print("\n=== Multilabel Neural Net ===")
X, y = make_multilabel_classification(n_samples=1200, n_features=20,
                                      n_classes=5, n_labels=2,
                                      random_state=RANDOM_STATE)
X = StandardScaler().fit_transform(X)

X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.3, random_state=RANDOM_STATE)

model_ml = models.Sequential([
    layers.Input(shape=(X.shape[1],)),   # ✅ FIXED
    layers.Dense(64, activation="relu"),
    layers.Dropout(0.3),
    layers.Dense(32, activation="relu"),
    layers.Dense(y.shape[1], activation="sigmoid")
])
model_ml.compile(optimizer="adam",
                 loss="binary_crossentropy",
                 metrics=["accuracy"])

hist_ml = model_ml.fit(X_train, y_train, validation_data=(X_test, y_test),
                       epochs=30, batch_size=32, verbose=0)

plot_learning_curves(hist_ml, "Multilabel — Learning Curves")

y_prob = model_ml.predict(X_test)
y_pred = (y_prob>=0.5).astype(int)

print(classification_report(y_test, y_pred, zero_division=0))
print("Subset Accuracy:", (y_test==y_pred).all(axis=1).mean())
print("Hamming Loss:", hamming_loss(y_test, y_pred))
print("Jaccard (Micro):", jaccard_score(y_test, y_pred, average="micro"))

# ROC/PR per label (first 3 labels shown)
for j in range(min(3, y.shape[1])):
    plot_roc_pr(y_test[:,j], y_prob[:,j], f"Label {j}")