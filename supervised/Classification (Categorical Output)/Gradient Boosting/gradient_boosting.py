print("\n=== Multilabel: Gradient Boosting (OvR, GPU) ===")
Xl, yl = make_multilabel_classification(n_samples=1600, n_features=30, n_classes=6, n_labels=2, random_state=RANDOM_STATE)

def ovr_model(builder): return OneVsRestClassifier(builder())

builders_ml = {
    "XGBoost": lambda: XGBClassifier(
        n_estimators=400, learning_rate=0.06, max_depth=4,
        subsample=0.9, colsample_bytree=0.9, eval_metric="logloss",
        random_state=RANDOM_STATE, n_jobs=-1,
        tree_method="gpu_hist", predictor="gpu_predictor"
    ),
    "LightGBM": lambda: LGBMClassifier(
        n_estimators=400, learning_rate=0.06, max_depth=-1,
        subsample=0.9, colsample_bytree=0.9,
        objective="binary", random_state=RANDOM_STATE,
        device="gpu", verbosity=-1, force_col_wise=True
    ),
    "CatBoost": lambda: CatBoostClassifier(
        iterations=400, learning_rate=0.06, depth=6,
        loss_function="Logloss", random_seed=RANDOM_STATE,
        verbose=False, task_type="GPU"
    )
}

for name, builder in builders_ml.items():
    clf = ovr_model(builder)
    y_pred = cross_val_predict(clf, Xl, yl, cv=5, method="predict")
    print(f"\n{name} — Classification Report (Multilabel):\n", classification_report(yl, y_pred, zero_division=0))
    print("Subset Accuracy:", (yl == y_pred).all(axis=1).mean())
