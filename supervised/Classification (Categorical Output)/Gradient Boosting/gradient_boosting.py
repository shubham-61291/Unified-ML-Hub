def threshold_tuning_table(y_test, y_prob, C_FP=1, C_FN=10, title="Threshold Tuning"):
    thresholds = np.linspace(0,1,1001)
    precisions, recalls, f1s, j_stats, costs, fprs, tprs = ([] for _ in range(7))
    for t in thresholds:
        preds = (y_prob >= t).astype(int)
        TP = np.sum((preds==1) & (y_test==1))
        FP = np.sum((preds==1) & (y_test==0))
        FN = np.sum((preds==0) & (y_test==1))
        TN = np.sum((preds==0) & (y_test==0))
        precision = TP/(TP+FP) if (TP+FP)>0 else 0.0
        recall = TP/(TP+FN) if (TP+FN)>0 else 0.0
        f1 = f1_score(y_test, preds, zero_division=0)
        tpr = recall
        fpr = FP/(FP+TN) if (FP+TN)>0 else 0.0
        j = tpr - fpr
        cost = FP*C_FP + FN*C_FN
        precisions.append(precision); recalls.append(recall); f1s.append(f1)
        j_stats.append(j); costs.append(cost); fprs.append(fpr); tprs.append(tpr)
    precisions, recalls, f1s, j_stats, costs = map(np.array, [precisions, recalls, f1s, j_stats, costs])
    idx_f1, idx_j, idx_c = np.argmax(f1s), np.argmax(j_stats), np.argmin(costs)
    print(f"\nOptimal Thresholds — {title}")
    print(f"F1-max: {thresholds[idx_f1]:.3f}, J-max: {thresholds[idx_j]:.3f}, Cost-min: {thresholds[idx_c]:.3f}")
    return [thresholds[idx_f1], thresholds[idx_j], thresholds[idx_c]]

def plot_perm_importance(estimator, X_val, y_val, feature_names, title="Permutation Importance", top_k=15, scoring='neg_log_loss'):
    r = permutation_importance(estimator, X_val, y_val, n_repeats=10, random_state=RANDOM_STATE, n_jobs=-1, scoring=scoring)
    imp, std = r.importances_mean, r.importances_std
    idx = np.argsort(imp)[::-1][:top_k]
    plt.figure(figsize=(8, max(5, len(idx)*0.3)))
    plt.barh(np.array(feature_names)[idx][::-1], imp[idx][::-1], xerr=std[idx][::-1])
    plt.title(title); plt.xlabel("Decrease in score"); plt.show()

