def cm_heatmap(cm, title, cmap="Blues"):
    sns.heatmap(cm, annot=True, fmt="d", cmap=cmap)
    plt.title(title); plt.xlabel("Predicted"); plt.ylabel("Actual"); plt.show()

def roc_pr_with_thresholds_binary(y_true, y_prob, title="", mark_thresholds=None):
    fpr, tpr, thr_roc = roc_curve(y_true, y_prob)
    precision, recall, thr_pr = precision_recall_curve(y_true, y_prob)
    avg_prec = average_precision_score(y_true, y_prob)
    roc_auc = auc(fpr, tpr)

    fig, axs = plt.subplots(1,2, figsize=(14,6))
    # ROC
    axs[0].plot(fpr, tpr, label=f"AUC={roc_auc:.3f}")
    axs[0].plot([0,1],[0,1],'k--', lw=1)
    axs[0].set_title(f"ROC Curve - {title}")
    axs[0].set_xlabel("False Positive Rate"); axs[0].set_ylabel("True Positive Rate")
    axs[0].legend()
    for i in range(0, len(thr_roc), max(1, len(thr_roc)//10)):
        axs[0].annotate(f"{thr_roc[i]:.2f}", (fpr[i], tpr[i]))
    # PR
    axs[1].plot(recall, precision, label=f"AP={avg_prec:.3f}")
    axs[1].set_title(f"PR Curve - {title}")
    axs[1].set_xlabel("Recall"); axs[1].set_ylabel("Precision")
    axs[1].legend()
    for i in range(0, len(thr_pr), max(1, len(thr_pr)//10)):
        idx = i
        axs[1].annotate(f"{thr_pr[i]:.2f}", (recall[idx], precision[idx]))
    # Mark thresholds
    if mark_thresholds:
        for t in mark_thresholds:
            idx_r = np.argmin(np.abs(thr_roc - t))
            axs[0].scatter(fpr[idx_r], tpr[idx_r], s=80, edgecolor='k', zorder=3)
            axs[0].annotate(f"t={t:.2f}", (fpr[idx_r], tpr[idx_r]))
            if len(thr_pr) > 0:
                idx_p = np.argmin(np.abs(thr_pr - t))
                axs[1].scatter(recall[idx_p], precision[idx_p], s=80, edgecolor='k', zorder=3)
                axs[1].annotate(f"t={t:.2f}", (recall[idx_p], precision[idx_p]))
    plt.show()

def plot_ovr_roc_pr(y_true, y_prob, class_names, title_prefix="GBM"):
    # ROC OvR
    plt.figure(figsize=(8,6))
    for i, cname in enumerate(class_names):
        fpr, tpr, _ = roc_curve((y_true==i).astype(int), y_prob[:,i])
        plt.plot(fpr, tpr, label=f"{cname} (AUC={auc(fpr,tpr):.3f})")
    plt.plot([0,1],[0,1],'k--', lw=1)
    plt.title(f"ROC Curves — Multiclass (OvR) — {title_prefix}")
    plt.xlabel("FPR"); plt.ylabel("TPR"); plt.legend(); plt.show()

    # PR OvR
    plt.figure(figsize=(8,6))
    for i, cname in enumerate(class_names):
        precision, recall, _ = precision_recall_curve((y_true==i).astype(int), y_prob[:,i])
        ap = average_precision_score((y_true==i).astype(int), y_prob[:,i])
        plt.plot(recall, precision, label=f"{cname} (AP={ap:.3f})")
    plt.title(f"PR Curves — Multiclass (OvR) — {title_prefix}")
    plt.xlabel("Recall"); plt.ylabel("Precision"); plt.legend(); plt.show()

def threshold_tuning_table(y_test, y_prob, C_FP=1, C_FN=10, title="Threshold Tuning"):
    thresholds = np.linspace(0,1,1001)
    precisions, recalls, f1s, j_stats, costs, fprs, tprs, tps, fps, fns, tns = ([] for _ in range(11))
    for t in thresholds:
        preds = (y_prob >= t).astype(int)
        TP = np.sum((preds==1) & (y_test==1))
        FP = np.sum((preds==1) & (y_test==0))
        FN = np.sum((preds==0) & (y_test==1))
        TN = np.sum((preds==0) & (y_test==0))
        precision = TP/(TP+FP) if (TP+FP)>0 else 0.0
        recall = TP/(TP+FN) if (TP+FN)>0 else 0.0
        f1 = f1_score(y_test, preds, zero_division=0)
        tpr = recall
        fpr = FP/(FP+TN) if (FP+TN)>0 else 0.0
        j = tpr - fpr
        cost = FP*C_FP + FN*C_FN
        precisions.append(precision); recalls.append(recall); f1s.append(f1)
        j_stats.append(j); costs.append(cost); fprs.append(fpr); tprs.append(tpr)
        tps.append(TP); fps.append(FP); fns.append(FN); tns.append(TN)
    precisions = np.array(precisions); recalls = np.array(recalls)
    f1s = np.array(f1s); j_stats = np.array(j_stats); costs = np.array(costs)
    fprs = np.array(fprs); tprs = np.array(tprs)
    tps = np.array(tps); fps = np.array(fps); fns = np.array(fns); tns = np.array(tns)
    idx_f1 = np.argmax(f1s); idx_j = np.argmax(j_stats); idx_c = np.argmin(costs)
    opt_table = pd.DataFrame([
        ["F1-max", thresholds[idx_f1], precisions[idx_f1], recalls[idx_f1], f1s[idx_f1], j_stats[idx_f1],
         costs[idx_f1], fprs[idx_f1], tprs[idx_f1], int(tps[idx_f1]), int(fps[idx_f1]), int(fns[idx_f1]), int(tns[idx_f1])],
        ["J-max", thresholds[idx_j], precisions[idx_j], recalls[idx_j], f1s[idx_j], j_stats[idx_j],
         costs[idx_j], fprs[idx_j], tprs[idx_j], int(tps[idx_j]), int(fps[idx_j]), int(fns[idx_j]), int(tns[idx_j])],
        ["Cost-min", thresholds[idx_c], precisions[idx_c], recalls[idx_c], f1s[idx_c], j_stats[idx_c],
         costs[idx_c], fprs[idx_c], tprs[idx_c], int(tps[idx_c]), int(fps[idx_c]), int(fns[idx_c]), int(tns[idx_c])]
    ], columns=["Criterion","Threshold","Precision","Recall","F1","Youden_J","Cost","FPR","TPR","TP","FP","FN","TN"])
    print(f"\nOptimal Thresholds — {title}")
    print(opt_table.to_string(index=False, float_format=lambda x: f"{x:.3f}" if isinstance(x,float) else str(x)))

    # Plot curves
    plt.figure(figsize=(12,6))
    plt.plot(thresholds, precisions, label="Precision")
    plt.plot(thresholds, recalls, label="Recall")
    plt.plot(thresholds, f1s, label="F1")
    plt.plot(thresholds, j_stats, label="Youden's J")
    plt.plot(thresholds, costs, label=f"Cost (C_FN={C_FN}, C_FP={C_FP})")
    for idx, name in [(idx_f1,"F1-max"), (idx_j,"J-max"), (idx_c,"Cost-min")]:
        t = [thresholds[idx]][0]
        plt.scatter([t],[f1s[idx]], s=80, edgecolor='k', label=f"{name} (t={t:.3f})")
    plt.axvline(0.5, color='k', linestyle='--', lw=1, label="Default t=0.5")
    plt.xlabel("Threshold"); plt.ylabel("Score / Cost")
    plt.title(f"Threshold Tuning — {title}")
    plt.legend(); plt.show()
    return [thresholds[idx_f1], thresholds[idx_j], thresholds[idx_c]]

def plot_perm_importance(estimator, X_val, y_val, feature_names, title="Permutation Importance", top_k=15, scoring='neg_log_loss'):
    r = permutation_importance(estimator, X_val, y_val, n_repeats=10, random_state=RANDOM_STATE, n_jobs=-1, scoring=scoring)
    imp = r.importances_mean; std = r.importances_std
    idx = np.argsort(imp)[::-1][:top_k]
    plt.figure(figsize=(8, max(5, len(idx)*0.3)))
    plt.barh(np.array(feature_names)[idx][::-1], imp[idx][::-1], xerr=std[idx][::-1])
    plt.title(title); plt.xlabel("Decrease in score"); plt.show()

