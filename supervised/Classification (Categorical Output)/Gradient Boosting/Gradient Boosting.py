print("\n=== Binary: Gradient Boosting on Breast Cancer ===")
breast = load_breast_cancer()
Xb, yb = breast.data, breast.target
feat_b = breast.feature_names

models_binary = {
    "XGBoost": XGBClassifier(
        n_estimators=600, learning_rate=0.05, max_depth=4, subsample=0.9, colsample_bytree=0.9,
        eval_metric="logloss", random_state=RANDOM_STATE, n_jobs=-1, tree_method="hist"
    ),
    "LightGBM": LGBMClassifier(
        n_estimators=600, learning_rate=0.05, max_depth=-1, subsample=0.9, colsample_bytree=0.9,
        objective="binary", random_state=RANDOM_STATE, n_jobs=-1,
        # ---- PATCHES ----
        min_child_samples=5, min_gain_to_split=1e-4,
        force_col_wise=True, verbosity=-1
    ),
    "CatBoost": CatBoostClassifier(
        iterations=600, learning_rate=0.05, depth=6, loss_function="Logloss",
        random_seed=RANDOM_STATE, verbose=False
    )
}

# CV configuration
cv = StratifiedKFold(n_splits=5, shuffle=True, random_state=RANDOM_STATE)
scoring_bin = {
    "accuracy":"accuracy", "precision":"precision", "recall":"recall", "f1":"f1",
    "roc_auc":"roc_auc", "neg_log_loss":"neg_log_loss"
}

for name, model in models_binary.items():
    print(f"\n--- {name}: 5-fold Cross-Validation ---")
    # CV uses the constructor params; LightGBM verbosity is silenced.
    cvres = cross_validate(model, Xb, yb, cv=cv, scoring=scoring_bin)
    for k in scoring_bin.keys():
        vals = cvres[f"test_{k}"]; print(f"{k:>12}: {vals.mean():.4f} ± {vals.std():.4f}")

    # Train/Test detailed eval
    Xtr, Xte, ytr, yte = train_test_split(Xb, yb, stratify=yb, test_size=0.3, random_state=RANDOM_STATE)
    if name == "LightGBM":
        # ---- PATCH: early stopping + eval_metric, silent fit ----
        model.fit(
            Xtr, ytr,
            eval_set=[(Xtr,ytr),(Xte,yte)],
            eval_metric="logloss",
            early_stopping_rounds=50,
            verbose=False
        )
    elif name == "XGBoost":
        model.fit(Xtr, ytr, eval_set=[(Xtr,ytr),(Xte,yte)], verbose=False)
    else:
        model.fit(Xtr, ytr, eval_set=[(Xte,yte)], verbose=False)

    ypred = model.predict(Xte)
    yprob = model.predict_proba(Xte)[:,1]

    print(f"\n{name} — Classification Report (Binary):\n", classification_report(yte, ypred, zero_division=0))
    print("Log Loss:", round(log_loss(yte, yprob), 6))
    print("Brier Score:", round(brier_score_loss(yte, yprob), 6))
    print("MCC:", round(matthews_corrcoef(yte, ypred), 6))
    if name == "LightGBM" and hasattr(model, "best_iteration_"):
        print("Best iteration used:", model.best_iteration_)

    cm = confusion_matrix(yte, ypred)
    cm_heatmap(cm, f"Confusion Matrix — Binary ({name})")

    # ROC/PR annotated
    roc_pr_with_thresholds_binary(yte, yprob, title=f"{name} (Binary)")

    # Calibration
    CalibrationDisplay.from_predictions(yte, yprob, n_bins=10)
    plt.title(f"Calibration Curve — Binary ({name})"); plt.show()

    # Threshold tuning + optima + mark on ROC/PR
    opt_ts = threshold_tuning_table(yte, yprob, C_FP=1, C_FN=10, title=f"{name} (Binary)")
    roc_pr_with_thresholds_binary(yte, yprob, title=f"{name} (Binary) — Optima Marked", mark_thresholds=opt_ts)

    # Feature importance (built-in gain/impurity)
    if name == "XGBoost":
        importances = model.feature_importances_
    elif name == "LightGBM":
        importances = model.feature_importances_
    else:  # CatBoost
        importances = model.get_feature_importance()
    order = np.argsort(importances)[::-1][:20]
    plt.figure(figsize=(8,6))
    plt.barh(np.array(feat_b)[order][::-1], importances[order][::-1])
    plt.title(f"Top Feature Importances — {name} (Binary)")
    plt.xlabel("Importance"); plt.show()

    # Permutation importance
    plot_perm_importance(model, Xte, yte, feat_b, title=f"Permutation Importance — {name} (Binary)", top_k=15)

    # SHAP summary
    try:
        explainer = shap.TreeExplainer(model)
        shap_vals = explainer.shap_values(Xte)
        plt.title(f"SHAP Summary — {name} (Binary)")
        shap.summary_plot(shap_vals if isinstance(shap_vals, np.ndarray) else shap_vals[1], Xte, feature_names=feat_b, show=False)
        plt.show()
    except Exception as e:
        print(f"SHAP failed for {name}: {e}")

