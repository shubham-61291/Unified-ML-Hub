import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

from sklearn.datasets import load_breast_cancer, load_iris, make_multilabel_classification
from sklearn.model_selection import train_test_split, StratifiedKFold, cross_validate, cross_val_predict
from sklearn.preprocessing import StandardScaler
from sklearn.linear_model import LogisticRegression
from sklearn.multiclass import OneVsRestClassifier
from sklearn.metrics import (
    confusion_matrix, classification_report, roc_curve, auc,
    precision_recall_curve, average_precision_score, log_loss,
    brier_score_loss, matthews_corrcoef, roc_auc_score, f1_score,
    hamming_loss, jaccard_score
)

sns.set(style="whitegrid", rc={"figure.figsize": (8,6)})

# ------------------------------
# Helper: ROC/PR with annotations
# ------------------------------
def plot_curves_with_thresholds(y_true, y_prob, title="", mark_thresholds=None):
    fpr, tpr, thr_roc = roc_curve(y_true, y_prob)
    precision, recall, thr_pr = precision_recall_curve(y_true, y_prob)
    avg_prec = average_precision_score(y_true, y_prob)
    roc_auc = auc(fpr, tpr)

    fig, axs = plt.subplots(1,2, figsize=(14,6))

    # ROC
    axs[0].plot(fpr, tpr, label=f"AUC={roc_auc:.3f}")
    axs[0].plot([0,1],[0,1],'k--', lw=1)
    axs[0].set_title(f"ROC Curve - {title}")
    axs[0].set_xlabel("False Positive Rate")
    axs[0].set_ylabel("True Positive Rate")
    axs[0].legend()

    # PR
    axs[1].plot(recall, precision, label=f"AP={avg_prec:.3f}")
    axs[1].set_title(f"PR Curve - {title}")
    axs[1].set_xlabel("Recall")
    axs[1].set_ylabel("Precision")
    axs[1].legend()

    # Annotate a few thresholds along the curves
    for i in range(0, len(thr_roc), max(1, len(thr_roc)//10)):
        axs[0].annotate(f"{thr_roc[i]:.2f}", (fpr[i], tpr[i]))
    for i in range(0, len(thr_pr), max(1, len(thr_pr)//10)):
        # thr_pr is length n-1; recall/precision are length n
        idx = i
        axs[1].annotate(f"{thr_pr[i]:.2f}", (recall[idx], precision[idx]))

    # Mark chosen thresholds (if any)
    if mark_thresholds:
        for t in mark_thresholds:
            # nearest on ROC
            idx_r = np.argmin(np.abs(thr_roc - t))
            axs[0].scatter(fpr[idx_r], tpr[idx_r], s=80, edgecolor='k', zorder=3)
            axs[0].annotate(f"t={t:.2f}", (fpr[idx_r], tpr[idx_r]))
            # nearest on PR
            if len(thr_pr) > 0:
                idx_p = np.argmin(np.abs(thr_pr - t))
                axs[1].scatter(recall[idx_p], precision[idx_p], s=80, edgecolor='k', zorder=3)
                axs[1].annotate(f"t={t:.2f}", (recall[idx_p], precision[idx_p]))

    plt.show()

# ==========================================================
# 1) Binary Classification (Breast Cancer) with CV + Threshold Tuning
# ==========================================================
print("\n=== Binary Classification (Breast Cancer) ===")
X, y = load_breast_cancer(return_X_y=True)

scaler = StandardScaler()
X = scaler.fit_transform(X)

model_bin = LogisticRegression(max_iter=1000, solver="lbfgs")

# ---- 5-fold CV (stable metrics)
cv = StratifiedKFold(n_splits=5, shuffle=True, random_state=42)
scoring = ["accuracy", "precision", "recall", "f1", "roc_auc", "neg_log_loss"]
cv_results = cross_validate(model_bin, X, y, cv=cv, scoring=scoring)

print("\nCross-Validation Results (Binary, 5-fold):")
for metric in scoring:
    scores = cv_results[f'test_{metric}']
    print(f"{metric:>12}: {scores.mean():.4f} ± {scores.std():.4f}")

# ---- Train/Test for detailed eval + plots + threshold tuning
X_train, X_test, y_train, y_test = train_test_split(X, y, stratify=y, test_size=0.3, random_state=42)
model_bin.fit(X_train, y_train)

y_pred = model_bin.predict(X_test)
y_prob = model_bin.predict_proba(X_test)[:,1]

print("\nClassification Report (Binary):\n", classification_report(y_test, y_pred, zero_division=0))
print("Log Loss:", round(log_loss(y_test, y_prob), 6))
print("Brier Score:", round(brier_score_loss(y_test, y_prob), 6))
print("MCC:", round(matthews_corrcoef(y_test, y_pred), 6))

cm = confusion_matrix(y_test, y_pred)
sns.heatmap(cm, annot=True, fmt="d", cmap="Blues")
plt.title("Confusion Matrix - Binary")
plt.xlabel("Predicted"); plt.ylabel("Actual")
plt.show()

# ROC + PR with thresholds annotated
plot_curves_with_thresholds(y_test, y_prob, title="Binary Logistic Regression")

# ---- Threshold tuning (Precision/Recall/F1/J/Cost) + Optimal Thresholds Table
thresholds = np.linspace(0, 1, 1001)  # fine grid for precise optima
precisions, recalls, f1s, j_stats, costs, fprs, tprs, tps, fps, fns, tns = ([] for _ in range(11))
C_FP, C_FN = 1, 10  # example costs; change as per business

for t in thresholds:
    preds = (y_prob >= t).astype(int)
    TP = np.sum((preds==1) & (y_test==1))
    FP = np.sum((preds==1) & (y_test==0))
    FN = np.sum((preds==0) & (y_test==1))
    TN = np.sum((preds==0) & (y_test==0))

    p = TP/(TP+FP) if (TP+FP)>0 else 0.0
    r = TP/(TP+FN) if (TP+FN)>0 else 0.0
    f1 = f1_score(y_test, preds, zero_division=0)
    tpr = r
    fpr = FP/(FP+TN) if (FP+TN)>0 else 0.0
    j = tpr - fpr
    cost = FP*C_FP + FN*C_FN

    precisions.append(p); recalls.append(r); f1s.append(f1); j_stats.append(j); costs.append(cost)
    fprs.append(fpr); tprs.append(tpr)
    tps.append(TP); fps.append(FP); fns.append(FN); tns.append(TN)

precisions = np.array(precisions); recalls = np.array(recalls)
f1s = np.array(f1s); j_stats = np.array(j_stats); costs = np.array(costs)
fprs = np.array(fprs); tprs = np.array(tprs)
tps = np.array(tps); fps = np.array(fps); fns = np.array(fns); tns = np.array(tns)

idx_f1 = np.argmax(f1s)
idx_j  = np.argmax(j_stats)
idx_c  = np.argmin(costs)

opt_rows = [
    ("F1-max", thresholds[idx_f1], precisions[idx_f1], recalls[idx_f1], f1s[idx_f1], j_stats[idx_f1],
     costs[idx_f1], fprs[idx_f1], tprs[idx_f1], int(tps[idx_f1]), int(fps[idx_f1]), int(fns[idx_f1]), int(tns[idx_f1])),
    ("J-max",  thresholds[idx_j ], precisions[idx_j ], recalls[idx_j ], f1s[idx_j ], j_stats[idx_j ],
     costs[idx_j ], fprs[idx_j ], tprs[idx_j ], int(tps[idx_j ]), int(fps[idx_j ]), int(fns[idx_j ]), int(tns[idx_j ])),
    ("Cost-min", thresholds[idx_c], precisions[idx_c], recalls[idx_c], f1s[idx_c], j_stats[idx_c],
     costs[idx_c], fprs[idx_c], tprs[idx_c], int(tps[idx_c]), int(fps[idx_c]), int(fns[idx_c]), int(tns[idx_c]))
]
opt_table = pd.DataFrame(
    opt_rows,
    columns=["Criterion","Threshold","Precision","Recall","F1","Youden_J","Cost","FPR","TPR","TP","FP","FN","TN"]
)
print("\nOptimal Thresholds (Binary) — Comparison Table")
display(opt_table.style.format({
    "Threshold":"{:.3f}","Precision":"{:.3f}","Recall":"{:.3f}","F1":"{:.3f}",
    "Youden_J":"{:.3f}","Cost":"{:.0f}","FPR":"{:.3f}","TPR":"{:.3f}"
}))

# Plot threshold metrics + highlight chosen thresholds
plt.figure(figsize=(12,6))
plt.plot(thresholds, precisions, label="Precision")
plt.plot(thresholds, recalls, label="Recall")
plt.plot(thresholds, f1s, label="F1")
plt.plot(thresholds, j_stats, label="Youden's J")
plt.plot(thresholds, costs, label=f"Cost (C_FN={C_FN}, C_FP={C_FP})")
for idx, name, color in [(idx_f1,"F1-max","C1"), (idx_j,"J-max","C2"), (idx_c,"Cost-min","C3")]:
    t = thresholds[idx]
    plt.scatter([t],[f1s[idx]], s=80, edgecolor='k', label=f"{name} (t={t:.3f})")
plt.axvline(0.5, color='k', linestyle='--', lw=1, label="Default t=0.5")
plt.xlabel("Threshold"); plt.ylabel("Score / Cost")
plt.title("Threshold Tuning — Binary Logistic Regression")
plt.legend()
plt.show()

# Also mark chosen thresholds on ROC/PR
plot_curves_with_thresholds(
    y_test, y_prob,
    title="Binary Logistic Regression (Optima Marked)",
    mark_thresholds=[thresholds[idx_f1], thresholds[idx_j], thresholds[idx_c]]
)

