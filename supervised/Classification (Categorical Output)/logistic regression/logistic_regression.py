# OvR ROC curves per class
y_prob = model_multi.predict_proba(X_test)
n_classes = len(np.unique(y))
plt.figure(figsize=(8,6))
for i in range(n_classes):
    fpr, tpr, _ = roc_curve((y_test==i).astype(int), y_prob[:,i])
    plt.plot(fpr, tpr, label=f"Class {i} (AUC={auc(fpr,tpr):.3f})")
plt.plot([0,1],[0,1],'k--', lw=1)
plt.title("ROC Curves - Multiclass (One-vs-Rest)")
