def cm_heatmap(cm, title, cmap="Blues"):
    sns.heatmap(cm, annot=True, fmt="d", cmap=cmap)
    plt.title(title); plt.xlabel("Predicted"); plt.ylabel("Actual"); plt.show()

def roc_pr_with_thresholds_binary(y_true, y_prob, title="", mark_thresholds=None):
    fpr, tpr, thr_roc = roc_curve(y_true, y_prob)
    precision, recall, thr_pr = precision_recall_curve(y_true, y_prob)
    avg_prec = average_precision_score(y_true, y_prob)
    roc_auc = auc(fpr, tpr)

    fig, axs = plt.subplots(1,2, figsize=(14,6))

    # ROC
    axs[0].plot(fpr, tpr, label=f"AUC={roc_auc:.3f}")
    axs[0].plot([0,1],[0,1],'k--', lw=1)
    axs[0].set_title(f"ROC Curve - {title}")
    axs[0].set_xlabel("False Positive Rate"); axs[0].set_ylabel("True Positive Rate")
    axs[0].legend()
    for i in range(0, len(thr_roc), max(1, len(thr_roc)//10)):
        axs[0].annotate(f"{thr_roc[i]:.2f}", (fpr[i], tpr[i]))

    # PR
    axs[1].plot(recall, precision, label=f"AP={avg_prec:.3f}")
    axs[1].set_title(f"PR Curve - {title}")
    axs[1].set_xlabel("Recall"); axs[1].set_ylabel("Precision")
    axs[1].legend()
    for i in range(0, len(thr_pr), max(1, len(thr_pr)//10)):
        idx = i
        axs[1].annotate(f"{thr_pr[i]:.2f}", (recall[idx], precision[idx]))

    if mark_thresholds:
        for t in mark_thresholds:
            # nearest points on ROC/PR
            idx_r = np.argmin(np.abs(thr_roc - t))
            axs[0].scatter(fpr[idx_r], tpr[idx_r], s=80, edgecolor='k', zorder=3)
            axs[0].annotate(f"t={t:.2f}", (fpr[idx_r], tpr[idx_r]))
            if len(thr_pr) > 0:
                idx_p = np.argmin(np.abs(thr_pr - t))
                axs[1].scatter(recall[idx_p], precision[idx_p], s=80, edgecolor='k', zorder=3)
                axs[1].annotate(f"t={t:.2f}", (recall[idx_p], precision[idx_p]))
    plt.show()

def plot_ovr_roc_pr(y_true, y_prob, class_names, title_prefix="Naïve Bayes"):
    # ROC OvR
    plt.figure(figsize=(8,6))
    for i, cname in enumerate(class_names):
        fpr, tpr, _ = roc_curve((y_true==i).astype(int), y_prob[:,i])
        plt.plot(fpr, tpr, label=f"{cname} (AUC={auc(fpr,tpr):.3f})")
    plt.plot([0,1],[0,1],'k--', lw=1)
    plt.title(f"ROC Curves — Multiclass (OvR) — {title_prefix}")
    plt.xlabel("FPR"); plt.ylabel("TPR"); plt.legend(); plt.show()

    # PR OvR
    plt.figure(figsize=(8,6))
    for i, cname in enumerate(class_names):
        precision, recall, _ = precision_recall_curve((y_true==i).astype(int), y_prob[:,i])
        ap = average_precision_score((y_true==i).astype(int), y_prob[:,i])
        plt.plot(recall, precision, label=f"{cname} (AP={ap:.3f})")
    plt.title(f"PR Curves — Multiclass (OvR) — {title_prefix}")
    plt.xlabel("Recall"); plt.ylabel("Precision"); plt.legend(); plt.show()

def feature_histograms_by_class(X, y, feature_names, class_names, top_features_idx=None, bins=30, title_prefix="Feature Dist"):
    # Plot distributions for selected features by class (GaussianNB assumption visualization)
    if top_features_idx is None:
        top_features_idx = list(range(min(2, X.shape[1])))
    for idx in top_features_idx:
        plt.figure(figsize=(8,5))
        for c in np.unique(y):
            sns.histplot(X[y==c, idx], bins=bins, kde=False, stat="density", label=f"{class_names[c]}", alpha=0.5)
        plt.title(f"{title_prefix}: {feature_names[idx]}")
        plt.xlabel(feature_names[idx]); plt.ylabel("Density"); plt.legend(); plt.show()

