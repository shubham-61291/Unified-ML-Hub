class RidgeRegressor:
    def __init__(self, l2=1e-2): self.l2=l2; self.w=None
    def fit(self, X, y):
        d = X.shape[1]
        A = X.T @ X + self.l2*np.eye(d)
        b = X.T @ y
        self.w = np.linalg.solve(A, b)
    def predict(self, X): return X @ self.w

