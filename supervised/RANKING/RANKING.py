# Listwise (ListNet)
class ListNetRanker:
    def __init__(self, lr=0.05, epochs=20): self.lr=lr; self.epochs=epochs; self.w=None
    def fit(self, groups, d:int):
        self.w=np.zeros(d)
        for _ in range(self.epochs):
            grad=np.zeros_like(self.w)
            for Xq,yq,_ in groups:
                P=np.exp(yq)/np.sum(np.exp(yq))
                s=Xq@self.w
                Q=np.exp(s)/np.sum(np.exp(s))
                grad += Xq.T@(Q-P)
            self.w -= self.lr*grad
    def predict(self,X): return X@self.w

