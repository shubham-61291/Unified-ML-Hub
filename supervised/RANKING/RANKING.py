# ----------------------------
# LambdaRank (pairwise lambda loss, neural scorer)
# ----------------------------
class LambdaRankNet(nn.Module):
    def __init__(self, d, hidden=[128, 64]):
        super().__init__()
        layers, prev = [], d
        for h in hidden:
            layers += [nn.Linear(prev, h), nn.ReLU()]
            prev = h
        layers += [nn.Linear(prev, 1)]
        self.net = nn.Sequential(*layers)
    def forward(self, x):
        return self.net(x).squeeze(-1)

def train_lambdarank(groups, d, epochs=12, lr=1e-3, l2=1e-4, max_pairs=None):
    model = LambdaRankNet(d).to(device)
    opt = optim.Adam(model.parameters(), lr=lr, weight_decay=l2)
    losses = []
    model.train()
    for ep in range(epochs):
        ep_loss = 0.0
        for Xq, yq, _ in groups:
            x = torch.tensor(Xq, dtype=torch.float32, device=device)
            y = torch.tensor(yq, dtype=torch.float32, device=device)
            s = model(x)
            # all pairs where y_i > y_j
            pairs = torch.nonzero(y.view(-1,1) > y.view(1,-1), as_tuple=False)
            if pairs.numel() == 0:
                continue
            if max_pairs is not None and pairs.shape[0] > max_pairs:
                idx = torch.randperm(pairs.shape[0])[:max_pairs]
                pairs = pairs[idx]
            i, j = pairs[:,0], pairs[:,1]
            sij = s[i] - s[j]
            loss = torch.log1p(torch.exp(-sij)).mean()
            opt.zero_grad()
            loss.backward()
            opt.step()
            ep_loss += loss.item()
        losses.append(ep_loss)
    return model, losses

