# Pairwise Logistic
class PairwiseLogisticRanker:
    def __init__(self, l2=1e-3, lr=0.05, epochs=20): self.l2=l2; self.lr=lr; self.epochs=epochs; self.w=None
    def fit(self, groups, d:int):
        self.w = np.zeros(d)
        for _ in range(self.epochs):
            grad=np.zeros_like(self.w)
            for Xq,yq,_ in groups:
                pairs=[(i,j) for i in range(len(yq)) for j in range(len(yq)) if yq[i]>yq[j]]
                for i,j in pairs:
                    xdiff=Xq[i]-Xq[j]
                    p=1/(1+np.exp(-(xdiff@self.w)))
                    grad += (p-1)*xdiff
            self.w -= self.lr*(grad+self.l2*self.w)
    def predict(self,X): return X@self.w

