# ----------------------------
# Deep ListNet (MLP + listwise softmax CE)
# ----------------------------
class DeepListNet(nn.Module):
    def __init__(self, d, hidden=[128, 64]):
        super().__init__()
        layers = []
        prev = d
        for h in hidden:
            layers += [nn.Linear(prev, h), nn.ReLU()]
            prev = h
        layers += [nn.Linear(prev, 1)]
        self.net = nn.Sequential(*layers)

    def forward(self, x):
        return self.net(x).squeeze(-1)

def _softmax_torch(v):
    v = v - v.max()
    ex = torch.exp(v)
    return ex / (ex.sum() + 1e-12)

def train_deeplistnet(groups, d, epochs=15, lr=1e-3, l2=1e-4):
    model = DeepListNet(d).to(device)
    opt = optim.Adam(model.parameters(), lr=lr, weight_decay=l2)
    losses = []
    model.train()
    for ep in range(epochs):
        ep_loss = 0.0
        for Xq, yq, _ in groups:
            x = torch.tensor(Xq, dtype=torch.float32, device=device)
            y = torch.tensor(yq, dtype=torch.float32, device=device)
            P = _softmax_torch(y)
            s = model(x)
            Q = _softmax_torch(s)
            loss = -(P * (Q.clamp_min(1e-12).log())).sum()
            opt.zero_grad()
            loss.backward()
            opt.step()
            ep_loss += loss.item()
        losses.append(ep_loss)
    return model, losses

