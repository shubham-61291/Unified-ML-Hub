def group_by_query(X, y, qids):
    return [(X[qids==q], y[qids==q], q) for q in np.unique(qids)]

def to_group_lengths(qids):
    return [int(np.sum(qids==q)) for q in np.unique(qids)]

def split_by_query(scores, y_full, qids_full):
    preds, truths = [], []
    start = 0
    for q in np.unique(qids_full):
        m = np.sum(qids_full == q)
        preds.append(np.asarray(scores)[start:start+m])
        truths.append(y_full[qids_full == q])
        start += m
    return truths, preds

def topk_table(y_true, scores, k=10):
    k = min(k, len(y_true))
    order = np.argsort(scores)[::-1][:k]
    return pd.DataFrame({"rank": np.arange(1,k+1),
                         "score": np.asarray(scores)[order].astype(float),
                         "true_grade": np.asarray(y_true)[order].astype(int)})

