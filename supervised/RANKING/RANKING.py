def dcg_at_k(rels, k):
    rels = np.asarray(rels)[:k]
    if rels.size == 0: return 0.0
    discounts = 1.0 / np.log2(np.arange(2, rels.size + 2))
    return float(np.sum((2**rels - 1) * discounts))

def ndcg_at_k(y_true, y_pred, k):
    idx = np.argsort(y_pred)[::-1]
    rels_pred = np.array(y_true)[idx]
    dcg = dcg_at_k(rels_pred, k)
    ideal = np.sort(y_true)[::-1]
    idcg = dcg_at_k(ideal, k)
    return 0.0 if idcg == 0 else dcg / idcg

def precision_at_k(y_true, y_pred, k, rel_threshold=2):
    y_true = np.array(y_true)
    relevant = y_true >= rel_threshold
    idx = np.argsort(y_pred)[::-1][:k]
    return float(np.mean(relevant[idx])) if len(idx) > 0 else 0.0

def average_precision(y_true, y_pred, rel_threshold=2):
    y_true = np.array(y_true)
    relevant = y_true >= rel_threshold
    order = np.argsort(y_pred)[::-1]
    rel_order = relevant[order]
    precisions, hits = [], 0
    for i, is_rel in enumerate(rel_order, start=1):
        if is_rel:
            hits += 1
            precisions.append(hits / i)
    return float(np.mean(precisions)) if len(precisions) > 0 else 0.0

def mean_average_precision(list_y_true, list_y_pred, rel_threshold=2):
    return float(np.mean([average_precision(t, p, rel_threshold) for t, p in zip(list_y_true, list_y_pred)]))

def mean_reciprocal_rank(list_y_true, list_y_pred, rel_threshold=2):
    rrs = []
    for t, p in zip(list_y_true, list_y_pred):
        t = np.array(t)
        relevant = t >= rel_threshold
        order = np.argsort(p)[::-1]
        rel_order = relevant[order]
        pos = np.where(rel_order)[0]
        rrs.append(1.0/(pos[0]+1) if len(pos)>0 else 0.0)
    return float(np.mean(rrs))

def evaluate_all(truth_groups, pred_groups, name):
    return {
        "Model": name,
        "NDCG@5":  np.mean([ndcg_at_k(t, p, 5) for t, p in zip(truth_groups, pred_groups)]),
        "NDCG@10": np.mean([ndcg_at_k(t, p, 10) for t, p in zip(truth_groups, pred_groups)]),
        "Precision@5 (rel>=2)": np.mean([precision_at_k(t, p, 5, 2) for t, p in zip(truth_groups, pred_groups)]),
        "MAP (rel>=2)": mean_average_precision(truth_groups, pred_groups, 2),
        "MRR (rel>=2)": mean_reciprocal_rank(truth_groups, pred_groups, 2)
    }

