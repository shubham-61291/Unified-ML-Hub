def build_mc_dropout_model(input_dim, dr=0.2, lr=1e-3):
    inp = keras.Input(shape=(input_dim,), dtype='float32')
    x = layers.Dense(128, activation='relu')(inp)
    x = layers.Dropout(dr)(x)
    x = layers.Dense(64, activation='relu')(x)
    x = layers.Dropout(dr)(x)
    x = layers.Dense(32, activation='relu')(x)
    x = layers.Dropout(dr)(x)
    out = layers.Dense(1, dtype='float32')(x)  # keep output in float32
    m = keras.Model(inp, out)
    opt = keras.optimizers.Adam(learning_rate=lr)
    m.compile(optimizer=opt, loss='mse', metrics=[keras.metrics.MeanAbsoluteError(name='mae')])
    return m

mc_model = build_mc_dropout_model(n_features, dr=0.2, lr=1e-3)
es = callbacks.EarlyStopping(monitor='val_loss', patience=20, mode='min', restore_best_weights=True, verbose=1)
rlr = callbacks.ReduceLROnPlateau(monitor='val_loss', factor=0.5, patience=5, min_lr=1e-6, verbose=1)
lrlog = LrLogger()
