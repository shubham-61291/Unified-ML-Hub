def metrics_block(y_true, y_pred, p=n_features, label=""):
    n = len(y_true)
    mse  = mean_squared_error(y_true, y_pred)
    rmse = float(np.sqrt(mse))
    mae  = mean_absolute_error(y_true, y_pred)
    r2   = r2_score(y_true, y_pred)
    adjr2 = 1 - (1 - r2) * (n - 1) / max(n - p - 1, 1)
    print(f"{label}MSE:{mse:.4f} RMSE:{rmse:.4f} MAE:{mae:.4f} R²:{r2:.4f} AdjR²:{adjr2:.4f}")
    return dict(MSE=mse, RMSE=rmse, MAE=mae, R2=r2, AdjR2=adjr2)

class LrLogger(callbacks.Callback):
    def on_train_begin(self, logs=None):
        self.history = []
    def on_epoch_end(self, epoch, logs=None):
        lr = float(tf.keras.backend.get_value(self.model.optimizer.learning_rate))
        self.history.append(lr)

def plot_loss_lr(history, lr_history, title_suffix=""):
    plt.figure(figsize=(8,5))
    plt.plot(history.history["loss"], label="Train")
    plt.plot(history.history["val_loss"], label="Val")
    plt.xlabel("Epoch"); plt.ylabel("Loss (MSE/NLL)")
    plt.title(f"Loss Curves {title_suffix}")
    plt.legend(); plt.show()

    plt.figure(figsize=(8,5))
    plt.plot(lr_history, marker='o')
    plt.xlabel("Epoch"); plt.ylabel("Learning Rate"); plt.yscale("log")
    plt.title(f"LR Schedule {title_suffix}"); plt.show()

def residual_plots(y_true, y_pred, tag=""):
    res = y_true - y_pred
    plt.figure(figsize=(12,5))
    plt.subplot(1,2,1)
    plt.scatter(y_true, y_pred, alpha=0.5)
    lo, hi = float(min(y_true.min(), y_pred.min())), float(max(y_true.max(), y_pred.max()))
    plt.plot([lo,hi],[lo,hi],'r--')
    plt.title(f"{tag}Actual vs Predicted"); plt.xlabel("Actual"); plt.ylabel("Predicted")
    plt.subplot(1,2,2)
    plt.scatter(y_pred, res, alpha=0.5)
    plt.axhline(0, color='r', linestyle='--')
    plt.title(f"{tag}Residuals vs Predicted"); plt.xlabel("Predicted"); plt.ylabel("Residuals")
    plt.tight_layout(); plt.show()

    plt.figure(figsize=(12,5))
    plt.subplot(1,2,1)
    sns.histplot(res, bins=30, kde=True)
    plt.title(f"{tag}Residual Distribution")
    plt.subplot(1,2,2)
    stats.probplot(res, dist="norm", plot=plt)
    plt.title(f"{tag}Q-Q Plot")
    plt.tight_layout(); plt.show()

