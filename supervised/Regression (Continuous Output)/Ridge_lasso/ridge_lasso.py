def coef_paths(model_name):
    paths = []
    for a in alphas:
        model = Ridge(alpha=a) if model_name=="Ridge" else Lasso(alpha=a, max_iter=20000)
        pipe  = Pipeline([("scaler", StandardScaler()), ("model", model)])
        pipe.fit(X_train, y_train)
        paths.append(pipe.named_steps["model"].coef_)
    paths = np.array(paths)
    plt.figure(figsize=(10,6))
    for j in range(paths.shape[1]):
        plt.plot(alphas, paths[:, j], label=feature_names[j], alpha=0.7)
    plt.xscale("log")
    plt.xlabel("Alpha"); plt.ylabel("Coefficient")
    plt.title(f"Coefficient Paths ({model_name})")
    plt.legend(bbox_to_anchor=(1.02,1), loc="upper left", fontsize="small")
    plt.show()

coef_paths("Ridge")
coef_paths("Lasso")

# -----------------------------
# 8) ELASTICNET HEATMAP (alpha x L1 ratio => Validation R²)
# -----------------------------
heat = np.zeros((len(alphas), len(l1_list)))
sc_tr = StandardScaler().fit(X_train)
Xtr_sc = sc_tr.transform(X_train)
Xva_sc = sc_tr.transform(X_val)

for i, a in enumerate(alphas):
    for j, l1 in enumerate(l1_list):
        en = ElasticNet(alpha=a, l1_ratio=l1, max_iter=10000)
        en.fit(Xtr_sc, y_train)
        yvp = en.predict(Xva_sc)
        heat[i, j] = r2_score(y_val, yvp)

plt.figure(figsize=(9,6))
sns.heatmap(heat, xticklabels=l1_list, yticklabels=np.round(alphas,3),
            cmap="viridis")
plt.xlabel("L1 Ratio"); plt.ylabel("Alpha")
plt.title("ElasticNet Validation R² (Alpha × L1)")
plt.show()

