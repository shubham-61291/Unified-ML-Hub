def diagnostics(model_name):
    yvp = results[model_name]["y_val_pred"]
    ytp = results[model_name]["y_test_pred"]

    # A) Actual vs Predicted + Residuals vs Predicted (2x2)
    plt.figure(figsize=(12,9))
    # Val: Actual vs Pred
    plt.subplot(2,2,1)
    plt.scatter(y_val, yvp, alpha=0.5)
    miv, mav = min(y_val.min(), yvp.min()), max(y_val.max(), yvp.max())
    plt.plot([miv,mav],[miv,mav],'--')
    plt.title(f"{model_name} | VAL: Actual vs Pred")
    plt.xlabel("Actual"); plt.ylabel("Predicted")

    # Val: Residuals vs Pred
    plt.subplot(2,2,2)
    plt.scatter(yvp, y_val - yvp, alpha=0.5)
    plt.axhline(0, linestyle="--")
    plt.title(f"{model_name} | VAL: Residuals vs Pred")
    plt.xlabel("Predicted"); plt.ylabel("Residuals")

    # Test: Actual vs Pred
    plt.subplot(2,2,3)
    plt.scatter(y_test, ytp, alpha=0.5)
    mit, mat = min(y_test.min(), ytp.min()), max(y_test.max(), ytp.max())
    plt.plot([mit,mat],[mit,mat],'--')
    plt.title(f"{model_name} | TEST: Actual vs Pred")
    plt.xlabel("Actual"); plt.ylabel("Predicted")

    # Test: Residuals vs Pred
    plt.subplot(2,2,4)
    plt.scatter(ytp, y_test - ytp, alpha=0.5)
    plt.axhline(0, linestyle="--")
    plt.title(f"{model_name} | TEST: Residuals vs Pred")
    plt.xlabel("Predicted"); plt.ylabel("Residuals")
    plt.tight_layout()
    plt.show()

    # B) Residual Hists + Q-Q (2x2)
    plt.figure(figsize=(12,9))
    # Val hist
    plt.subplot(2,2,1)
    sns.histplot(y_val - yvp, bins=30, kde=True)
    plt.title(f"{model_name} | VAL: Residual Histogram")
    # Test hist
    plt.subplot(2,2,2)
    sns.histplot(y_test - ytp, bins=30, kde=True)
    plt.title(f"{model_name} | TEST: Residual Histogram")
    # Val Q-Q
    plt.subplot(2,2,3)
    stats.probplot(y_val - yvp, dist="norm", plot=plt)
    plt.title(f"{model_name} | VAL: Q-Q")
    # Test Q-Q
    plt.subplot(2,2,4)
    stats.probplot(y_test - ytp, dist="norm", plot=plt)
    plt.title(f"{model_name} | TEST: Q-Q")
    plt.tight_layout()
    plt.show()

for m in ["Ordinary","Ridge","Lasso","ElasticNet"]:
    diagnostics(m)

