def bar_compare(metric_idx, metric_name):
    plt.figure(figsize=(10,5))
    labels = ["Ordinary", "Ridge", "Lasso", "ElasticNet"]
    val_vals = [results[m]["val"][metric_idx] for m in labels]
    test_vals= [results[m]["test"][metric_idx] for m in labels]
    x = np.arange(len(labels)); width=0.35
    plt.bar(x - width/2, val_vals,  width, label="Validation")
    plt.bar(x + width/2, test_vals, width, label="Test")
    plt.xticks(x, labels)
    plt.ylabel(metric_name)
    plt.title(f"{metric_name} Comparison")
    plt.legend()
    plt.show()

bar_compare(3, "R²")
bar_compare(1, "RMSE")
bar_compare(2, "MAE")

# -----------------------------
# 6) VALIDATION CURVES vs ALPHA (Ridge & Lasso): R² and RMSE
# -----------------------------
def validation_curve_alpha(model_name):
    r2_scores, rmse_scores, train_rmse = [], [], []
    for a in alphas:
        model = Ridge(alpha=a) if model_name=="Ridge" else Lasso(alpha=a, max_iter=20000)
        pipe  = Pipeline([("scaler", StandardScaler()), ("model", model)])
        pipe.fit(X_train, y_train)
        y_val_pred  = pipe.predict(X_val)
        y_train_pred= pipe.predict(X_train)
        # metrics
        mse_val  = mean_squared_error(y_val, y_val_pred)
        rmse_val = np.sqrt(mse_val)
        r2_val   = r2_score(y_val, y_val_pred)
        r2_scores.append(r2_val)
        rmse_scores.append(rmse_val)
        train_rmse.append(np.sqrt(mean_squared_error(y_train, y_train_pred)))
    # Plots
    plt.figure(figsize=(10,5))
    plt.semilogx(alphas, r2_scores, marker="o", label="Validation R²")
    plt.semilogx(alphas, rmse_scores, marker="s", label="Validation RMSE")
    plt.semilogx(alphas, train_rmse, marker="^", label="Train RMSE")
    plt.xlabel("Alpha"); plt.title(f"{model_name}: Metrics vs Alpha")
    plt.legend(); plt.show()

validation_curve_alpha("Ridge")
validation_curve_alpha("Lasso")

