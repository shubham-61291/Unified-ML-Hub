# 1) EARLY STOPPING model (native in sklearn)
# ==================================================
gbrt_es = GradientBoostingRegressor(
    n_estimators=2000,      # large upper bound
    learning_rate=0.05,
    max_depth=3,
    subsample=0.8,
    validation_fraction=0.2,
    n_iter_no_change=20,
    tol=1e-4,
    random_state=42
)
gbrt_es.fit(X_train, y_train)
print(f"✅ Early stopping chose {gbrt_es.n_estimators_} trees")

y_val_pred_es  = gbrt_es.predict(X_val)
y_test_pred_es = gbrt_es.predict(X_test)

val_es  = metrics_all(y_val,  y_val_pred_es,  n_features)
test_es = metrics_all(y_test, y_test_pred_es, n_features)
print_metrics_block("Validation Metrics (Early Stop)", val_es)
print_metrics_block("Test Metrics (Early Stop)",       test_es)

# Learning curves for ES model (staged predictions)
train_rmse_es, val_rmse_es = [], []
for y_tr_pred, y_va_pred in zip(gbrt_es.staged_predict(X_train), gbrt_es.staged_predict(X_val)):
    train_rmse_es.append(np.sqrt(mean_squared_error(y_train, y_tr_pred)))
    val_rmse_es.append(np.sqrt(mean_squared_error(y_val,   y_va_pred)))

plt.figure(figsize=(9,5))
plt.plot(train_rmse_es, label="Train RMSE")
plt.plot(val_rmse_es,   label="Validation RMSE")
plt.axvline(np.argmin(val_rmse_es), color="k", linestyle="--", label=f"Optimal Trees={np.argmin(val_rmse_es)}")
plt.xlabel("Number of Trees"); plt.ylabel("RMSE"); plt.title("Learning Curves (Early Stop Model)")
plt.legend(); plt.show()

