def neighbors(val, choices):
    # choose val and near neighbors if present in choices
    if isinstance(val, float):
        # pick closest three in choices
        arr = sorted(choices, key=lambda x: abs(x - val))[:3]
        return sorted(set(arr))
    if isinstance(val, int):
        nearby = sorted(set([val, max(min(val-1, max(choices)), min(choices)), min(max(val+1, min(choices)), max(choices))]))
        return [v for v in nearby if v in choices]
    return [val]

grid_choices = {
    "learning_rate":     [0.01, 0.03, 0.05, 0.1, 0.2],
    "max_depth":         [2, 3, 4, 5],
    "subsample":         [0.6, 0.8, 1.0],
    "n_estimators":      [400, 700, 1000, 1500],
    "min_samples_leaf":  [1, 2, 4],
    "min_samples_split": [2, 5, 10]
}
bp = rs.best_params_
param_grid = {
    "learning_rate":     neighbors(bp["learning_rate"], grid_choices["learning_rate"]),
    "max_depth":         neighbors(bp["max_depth"],     grid_choices["max_depth"]),
    "subsample":         neighbors(bp["subsample"],     grid_choices["subsample"]),
    "n_estimators":      neighbors(bp["n_estimators"],  grid_choices["n_estimators"]),
    "min_samples_leaf":  neighbors(bp["min_samples_leaf"],  grid_choices["min_samples_leaf"]),
    "min_samples_split": neighbors(bp["min_samples_split"], grid_choices["min_samples_split"]),
}

print("\nFocused Grid around RS best:")
print(param_grid)

