# Helpers (metrics + residuals)
# -----------------------------
def metrics_all(y_true, y_pred, p):
    n = len(y_true)
    mse  = mean_squared_error(y_true, y_pred)
    rmse = np.sqrt(mse)
    mae  = mean_absolute_error(y_true, y_pred)
    r2   = r2_score(y_true, y_pred)
    adjr2 = 1 - (1 - r2) * (n - 1) / max(n - p - 1, 1)
    return dict(MSE=mse, RMSE=rmse, MAE=mae, R2=r2, AdjR2=adjr2)

def print_metrics_block(title, m):
    print(f"\n{title}")
    print(f"MSE: {m['MSE']:.4f} | RMSE: {m['RMSE']:.4f} | MAE: {m['MAE']:.4f} | R²: {m['R2']:.4f} | Adj R²: {m['AdjR2']:.4f}")

def residual_diagnostics(y_true, y_pred, title_prefix=""):
    res = y_true - y_pred

    # Actual vs Predicted + Residuals vs Predicted
    plt.figure(figsize=(12,5))
    # A vs P
    plt.subplot(1,2,1)
    plt.scatter(y_true, y_pred, alpha=0.5)
    lo, hi = min(y_true.min(), y_pred.min()), max(y_true.max(), y_pred.max())
    plt.plot([lo,hi],[lo,hi],'r--')
    plt.title(f"{title_prefix}Actual vs Predicted")
    plt.xlabel("Actual"); plt.ylabel("Predicted")
    # Residuals vs Pred
    plt.subplot(1,2,2)
    plt.scatter(y_pred, res, alpha=0.5)
    plt.axhline(0, color="r", linestyle="--")
    plt.title(f"{title_prefix}Residuals vs Predicted")
    plt.xlabel("Predicted"); plt.ylabel("Residuals")
    plt.tight_layout()
    plt.show()

    # Residual hist + Q-Q
    plt.figure(figsize=(12,5))
    plt.subplot(1,2,1)
    sns.histplot(res, bins=30, kde=True)
    plt.title(f"{title_prefix}Residual Distribution")
    plt.subplot(1,2,2)
    stats.probplot(res, dist="norm", plot=plt)
    plt.title(f"{title_prefix}Q-Q Plot")
    plt.tight_layout()
    plt.show()

# -----------------------------
# Utility: staged-like RMSE curve for LightGBM (num_iteration)
# -----------------------------
def lgb_staged_rmse(estimator, X_tr, y_tr, X_va, y_va, max_iter=None):
    """
    Emulate staged_predict RMSE series using LightGBM predict with num_iteration.
    Returns (train_rmse_list, val_rmse_list)
    """
    if max_iter is None:
        # prefer best_iteration_ if available otherwise use n_estimators
        max_iter = getattr(estimator, "best_iteration_", None) or estimator.n_estimators
    # Ensure integer
    max_iter = int(max_iter)
    train_rmse = []
    val_rmse = []
    # iterate in steps to reduce overhead: step=1 to match original exactness
    for i in range(1, max_iter + 1):
        y_tr_pred = estimator.predict(X_tr, num_iteration=i)
        y_va_pred = estimator.predict(X_va, num_iteration=i)
        train_rmse.append(np.sqrt(mean_squared_error(y_tr, y_tr_pred)))
        val_rmse.append(np.sqrt(mean_squared_error(y_va, y_va_pred)))
    return train_rmse, val_rmse

